    /// Apply explicit UI name overrides after the original source contract has
    /// been identified and rebuilt. Name binding keeps SQL, literals, unrelated
    /// identifiers and the interface's own name intact.
    let ApplyGeneratedNames(sourceNamespace: string, sourceContextName: string, namespaceText: string,
                            contextText: string, generation: PocoGeneration, token: CancellationToken) =
        let targetNamespace = if String.IsNullOrWhiteSpace namespaceText then sourceNamespace else namespaceText.Trim()
        let targetContext = if String.IsNullOrWhiteSpace contextText then sourceContextName else contextText.Trim()
        if targetNamespace = sourceNamespace && targetContext = sourceContextName then generation
        else
            let namespaceUnit = CSharpSyntaxTree.ParseText("namespace " + targetNamespace + " {}", cancellationToken = token).GetCompilationUnitRoot(token)
            if namespaceUnit.ContainsDiagnostics || namespaceUnit.Members.Count <> 1
               || not (namespaceUnit.Members.[0] :? NamespaceDeclarationSyntax)
               || (namespaceUnit.DescendantNodes() |> Seq.exists (fun node -> node :? GenericNameSyntax || node :? AliasQualifiedNameSyntax)) then
                invalidArg (nameof namespaceText) "Enter a valid C# namespace, for example Company.Models."
            let parsedContext = SyntaxFactory.ParseName targetContext
            if not (parsedContext :? IdentifierNameSyntax) || parsedContext.ContainsDiagnostics
               || not (SyntaxFacts.IsValidIdentifier targetContext) then
                invalidArg (nameof contextText) "Enter a valid C# context class name."
            let sourceFullName = if String.IsNullOrWhiteSpace sourceNamespace then sourceContextName else sourceNamespace + "." + sourceContextName
            let movingGlobalTypes = String.IsNullOrWhiteSpace sourceNamespace && not (String.IsNullOrWhiteSpace targetNamespace)
            let namespaceName (space: INamespaceSymbol) = if space.IsGlobalNamespace then "" else space.ToDisplayString()
            let mapNamespace (value: string) =
                if value = sourceNamespace then targetNamespace
                elif not (String.IsNullOrWhiteSpace sourceNamespace) && value.StartsWith(sourceNamespace + ".", StringComparison.Ordinal) then
                    targetNamespace + value.Substring(sourceNamespace.Length)
                else value
            let codeFiles = generation.Files |> Array.filter (fun (file: PocoGeneratedFile) -> file.FileName.EndsWith(".cs", StringComparison.OrdinalIgnoreCase))
            let parseFiles (files: PocoGeneratedFile array) = files |> Array.map (fun file -> CSharpSyntaxTree.ParseText(file.Text, path = file.FileName, cancellationToken = token))
            let references = [| MetadataReference.CreateFromFile(typeof<obj>.Assembly.Location) :> MetadataReference |]
            let compile trees = CSharpCompilation.Create("AnotherEdit.GeneratedNames", syntaxTrees = trees, references = references,
                                                        options = CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary))
            let withNameTrivia (previous: NameSyntax) (value: string) =
                let replacement = SyntaxFactory.ParseName value
                let comments = previous.DescendantTrivia() |> Seq.filter (fun trivia ->
                    trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia)) |> Seq.toArray
                if comments.Length = 0 then replacement.WithTriviaFrom previous
                else replacement.WithLeadingTrivia(previous.GetLeadingTrivia().AddRange comments).WithTrailingTrivia(previous.GetTrailingTrivia())
            let firstTrees = parseFiles codeFiles
            let firstCompilation = compile firstTrees
            // A fully-qualified namespace can move across former nested namespace
            // boundaries. Flatten only those files, retaining scoped usings.
            let normalized =
                Array.map2 (fun (file: PocoGeneratedFile) (tree: SyntaxTree) ->
                    let root = tree.GetCompilationUnitRoot(token)
                    let nested = root.DescendantNodes().OfType<BaseNamespaceDeclarationSyntax>() |> Seq.exists (fun node -> node.Parent :? BaseNamespaceDeclarationSyntax)
                    if not nested then file
                    else
                        let semantic = firstCompilation.GetSemanticModel(tree, false)
                        let qualifyUsing (directive: UsingDirectiveSyntax) =
                            if isNull directive.Name then directive
                            else
                                let symbol = semantic.GetSymbolInfo(directive.Name, token).Symbol
                                if isNull symbol then directive
                                else directive.WithName(withNameTrivia directive.Name (symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)))
                        let rec flatten (inherited: UsingDirectiveSyntax array) (externs: ExternAliasDirectiveSyntax array) (memberNode: MemberDeclarationSyntax) =
                            seq {
                                match memberNode with
                                | :? BaseNamespaceDeclarationSyntax as scope ->
                                    let symbol = semantic.GetDeclaredSymbol(scope, token)
                                    let fullName = symbol.ToDisplayString()
                                    let usings = Array.append inherited (scope.Usings |> Seq.map qualifyUsing |> Seq.toArray)
                                    let externs = Array.append externs (scope.Externs |> Seq.toArray)
                                    let direct = scope.Members |> Seq.filter (fun item -> not (item :? BaseNamespaceDeclarationSyntax)) |> Seq.toArray
                                    if direct.Length > 0 then
                                        let declaration = SyntaxFactory.NamespaceDeclaration(SyntaxFactory.ParseName fullName)
                                                              .WithNamespaceKeyword(scope.NamespaceKeyword)
                                                              .WithUsings(SyntaxFactory.List usings).WithExterns(SyntaxFactory.List externs)
                                                              .WithMembers(SyntaxFactory.List direct).WithTriviaFrom(scope)
                                        yield declaration :> MemberDeclarationSyntax
                                    for child in scope.Members do
                                        if child :? BaseNamespaceDeclarationSyntax then yield! flatten usings externs child
                                | _ -> yield memberNode
                            }
                        let members = root.Members |> Seq.collect (flatten [||] [||])
                        { file with Text = root.WithMembers(SyntaxFactory.List members).ToFullString() }) codeFiles firstTrees
            let trees = parseFiles normalized
            let compilation = compile trees
            let contextSymbols =
                trees |> Array.collect (fun tree ->
                    let semantic = compilation.GetSemanticModel(tree, false)
                    tree.GetRoot(token).DescendantNodes().OfType<ClassDeclarationSyntax>()
                    |> Seq.choose (fun declaration ->
                        let symbol = semantic.GetDeclaredSymbol(declaration, token)
                        if not (isNull symbol) && symbol.ToDisplayString() = sourceFullName then Some(symbol :> ISymbol) else None)
                    |> Seq.toArray)
            if contextSymbols.Length = 0 then invalidOp ("The generated context could not be located: " + sourceFullName)
            let isContext (symbol: ISymbol) = not (isNull symbol) && (contextSymbols |> Array.exists (fun context -> SymbolEqualityComparer.Default.Equals(context, symbol)))
            let rec typePath (symbol: INamedTypeSymbol) =
                let prefix = if isNull symbol.ContainingType then "" else typePath symbol.ContainingType + "."
                prefix + (if isContext symbol then (parsedContext :?> IdentifierNameSyntax).Identifier.ValueText else symbol.Name) + "`" + string symbol.Arity
            let declaredNames =
                trees |> Array.collect (fun tree ->
                    let semantic = compilation.GetSemanticModel(tree, false)
                    tree.GetRoot(token).DescendantNodes().OfType<BaseTypeDeclarationSyntax>()
                    |> Seq.choose (fun declaration ->
                        match semantic.GetDeclaredSymbol(declaration, token) with
                        | symbol when not (isNull symbol) ->
                            let space = mapNamespace (namespaceName symbol.ContainingNamespace)
                            Some(space + "." + typePath symbol, symbol.ToDisplayString())
                        | _ -> None) |> Seq.toArray)
            declaredNames |> Array.groupBy fst |> Array.iter (fun (name, items) ->
                if items |> Array.map snd |> Array.distinct |> Array.length > 1 then
                    invalidArg (nameof contextText) ("The requested generated names would declare the same type twice: " + name))
            let renamed =
                Array.map2 (fun (file: PocoGeneratedFile) (tree: SyntaxTree) ->
                    token.ThrowIfCancellationRequested()
                    let root = tree.GetRoot(token)
                    let semantic = compilation.GetSemanticModel(tree, false)
                    let edits = ResizeArray<PocoExistingEdit>()
                    let covered (span: Text.TextSpan) = edits |> Seq.exists (fun edit -> edit.Start <= span.Start && span.End <= edit.Start + edit.Length)
                    let add (span: Text.TextSpan) replacement =
                        if not (covered span) && file.Text.Substring(span.Start, span.Length) <> replacement then
                            edits.Add { Id = Guid.NewGuid().ToString("N"); RelativePath = file.FileName; SourceHash = ""
                                        Description = "Use selected generated names"; Start = span.Start; Length = span.Length
                                        Replacement = replacement; RequiresReview = false }
                    let namespaceTextFor (node: SyntaxNode) value =
                        // Keep comments located between the old namespace tokens.
                        let comments = node.DescendantTrivia() |> Seq.filter (fun trivia ->
                            node.Span.Contains(trivia.Span) &&
                            (trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia)))
                        String.Concat(comments |> Seq.map (fun trivia -> trivia.ToFullString() + (if trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) then Environment.NewLine else " "))) + value
                    let mappedNamespace (node: SyntaxNode) (symbol: ISymbol) =
                        match symbol with
                        | :? INamespaceSymbol as space ->
                            let current = namespaceName space
                            let mapped = mapNamespace current
                            if mapped <> current then
                                let prefix = if node.ToString().StartsWith("global::", StringComparison.Ordinal) then "global::" else ""
                                add node.Span (namespaceTextFor node (prefix + mapped))
                        | _ -> ()
                    for declaration in root.DescendantNodes().OfType<ClassDeclarationSyntax>() do
                        if isContext (semantic.GetDeclaredSymbol(declaration, token)) then add declaration.Identifier.Span targetContext
                    for constructor in root.DescendantNodes().OfType<ConstructorDeclarationSyntax>() do
                        let symbol = semantic.GetDeclaredSymbol(constructor, token)
                        if not (isNull symbol) && isContext symbol.ContainingType then add constructor.Identifier.Span targetContext
                    for destructor in root.DescendantNodes().OfType<DestructorDeclarationSyntax>() do
                        let symbol = semantic.GetDeclaredSymbol(destructor, token)
                        if not (isNull symbol) && isContext symbol.ContainingType then add destructor.Identifier.Span targetContext
                    for scope in root.DescendantNodes().OfType<BaseNamespaceDeclarationSyntax>() do
                        let symbol = semantic.GetDeclaredSymbol(scope, token)
                        let current = symbol.ToDisplayString()
                        let mapped = mapNamespace current
                        if mapped <> current then add scope.Name.Span (namespaceTextFor scope.Name mapped)
                    if movingGlobalTypes then
                        // Global model types used to be visible from every
                        // namespace. Qualify their bound references before
                        // enclosing the declarations in the requested namespace.
                        for name in root.DescendantNodes().OfType<SimpleNameSyntax>() do
                            let aliased =
                                match name with
                                | :? IdentifierNameSyntax as identifier -> not (isNull (semantic.GetAliasInfo(identifier, token)))
                                | _ -> false
                            if not aliased then
                                match semantic.GetSymbolInfo(name, token).Symbol with
                                | :? INamedTypeSymbol as symbol when isNull symbol.ContainingType && symbol.ContainingNamespace.IsGlobalNamespace
                                                                       && (symbol.OriginalDefinition.Locations |> Seq.exists _.IsInSource) ->
                                    let identifier = if isContext symbol.OriginalDefinition then targetContext else name.Identifier.Text
                                    match name.Parent with
                                    | :? AliasQualifiedNameSyntax as qualified when qualified.Alias.Identifier.ValueText = "global" ->
                                        let prefix = Text.TextSpan.FromBounds(qualified.SpanStart, name.SpanStart)
                                        add prefix (file.Text.Substring(prefix.Start, prefix.Length) + targetNamespace + ".")
                                        add name.Identifier.Span identifier
                                    | _ -> add name.Identifier.Span ("global::" + targetNamespace + "." + identifier)
                                | _ -> ()
                    // Qualified namespace prefixes are replaced before their leaf
                    // tokens, so global::Old.Model.Context and static type access
                    // cannot acquire the replacement namespace more than once.
                    for node in root.DescendantNodes() |> Seq.filter (fun node -> node :? QualifiedNameSyntax || node :? AliasQualifiedNameSyntax || node :? MemberAccessExpressionSyntax) |> Seq.sortByDescending _.Span.Length do
                        if not (covered node.Span) then mappedNamespace node (semantic.GetSymbolInfo(node, token).Symbol)
                    for name in root.DescendantNodes().OfType<IdentifierNameSyntax>() do
                        if not (covered name.Span) && isNull (semantic.GetAliasInfo(name, token)) then
                            let symbol = semantic.GetSymbolInfo(name, token).Symbol
                            if isContext symbol then add name.Identifier.Span targetContext
                            else mappedNamespace name symbol
                    let updated = ApplyEdits(file.Text, edits.ToArray())
                    if not movingGlobalTypes then { file with Text = updated }
                    else
                        let unit = CSharpSyntaxTree.ParseText(updated, cancellationToken = token).GetCompilationUnitRoot(token)
                        let members = ResizeArray<MemberDeclarationSyntax>()
                        let globalTypes = ResizeArray<MemberDeclarationSyntax>()
                        let flushGlobalTypes () =
                            if globalTypes.Count > 0 then
                                let scope = SyntaxFactory.NamespaceDeclaration(SyntaxFactory.ParseName targetNamespace)
                                                .WithNamespaceKeyword(SyntaxFactory.Token(SyntaxKind.NamespaceKeyword).WithTrailingTrivia(SyntaxFactory.Space))
                                                .WithOpenBraceToken(SyntaxFactory.Token(SyntaxKind.OpenBraceToken).WithTrailingTrivia(SyntaxFactory.EndOfLine Environment.NewLine))
                                                .WithCloseBraceToken(SyntaxFactory.Token(SyntaxKind.CloseBraceToken).WithLeadingTrivia(SyntaxFactory.EndOfLine Environment.NewLine).WithTrailingTrivia(SyntaxFactory.EndOfLine Environment.NewLine))
                                                .WithMembers(SyntaxFactory.List globalTypes)
                                members.Add scope
                                globalTypes.Clear()
                        for memberNode in unit.Members do
                            if memberNode :? BaseTypeDeclarationSyntax || memberNode :? DelegateDeclarationSyntax then globalTypes.Add memberNode
                            else
                                flushGlobalTypes ()
                                members.Add memberNode
                        flushGlobalTypes ()
                        { file with Text = ApplyEdits(unit.WithMembers(SyntaxFactory.List members).ToFullString(), [||]) }) normalized trees
            let byPath = renamed |> Array.map (fun (file: PocoGeneratedFile) -> file.FileName, file) |> Map.ofArray
            { generation with Files = generation.Files |> Array.map (fun (file: PocoGeneratedFile) -> Map.tryFind file.FileName byPath |> Option.defaultValue file) }
