module PocoExistingModel =
    let private utf8 = UTF8Encoding(false, true)
    let private generatedMarker =
        Regex(@"^[\t ]*(?://|\*)[\t ]*<auto-generated(?:[\t ]*/)?[\t ]*>[\t \r]*$",
              RegexOptions.IgnoreCase ||| RegexOptions.Multiline)

    let private one values =
        match values |> Seq.distinct |> Seq.toArray with
        | [| value |] -> Some value
        | _ -> None

    let private simpleName (text: string) =
        let offset = max (text.LastIndexOf('.')) (text.LastIndexOf(':'))
        text.Substring(offset + 1).TrimStart('@')

    let private attributes name (lists: SyntaxList<AttributeListSyntax>) =
        lists |> Seq.collect _.Attributes |> Seq.filter (fun attribute ->
            let actual = simpleName (attribute.Name.ToString())
            actual = name || actual = name + "Attribute")

    let private literalText (expression: ExpressionSyntax) =
        match expression with
        | :? LiteralExpressionSyntax as literal when literal.IsKind(SyntaxKind.StringLiteralExpression) ->
            Some literal.Token.ValueText
        | _ -> None

    let private attributeValue name argument lists =
        attributes name lists
        |> Seq.choose (fun attribute ->
            if isNull attribute.ArgumentList then None
            else
                attribute.ArgumentList.Arguments
                |> Seq.tryFind (fun item ->
                    match argument with
                    | None -> isNull item.NameEquals && isNull item.NameColon
                    | Some name ->
                        (not (isNull item.NameEquals) && item.NameEquals.Name.Identifier.ValueText = name)
                        || (not (isNull item.NameColon) && item.NameColon.Name.Identifier.ValueText = name))
                |> Option.bind (fun item -> literalText item.Expression))
        |> one

    let private sourceName (node: SyntaxNode) name =
        let scopes =
            node.Ancestors()
            |> Seq.choose (function
                | :? BaseNamespaceDeclarationSyntax as item -> Some item.Name
                | _ -> None)
            |> Seq.rev
            |> Seq.map (fun name -> name.ToString().Replace("@", ""))
            |> String.concat "."
        let containing =
            node.Ancestors()
            |> Seq.choose (function
                | :? TypeDeclarationSyntax as item -> Some item.Identifier.ValueText
                | _ -> None)
            |> Seq.rev
        let fullName =
            Seq.concat [ Seq.singleton scopes; containing; Seq.singleton name ]
            |> Seq.filter (String.IsNullOrEmpty >> not)
            |> String.concat "."
        scopes, fullName

    let internal TypeDeclarations (root: SyntaxNode) =
        root.DescendantNodes()
        |> Seq.choose (fun node ->
            let name =
                match node with
                | :? TypeDeclarationSyntax as item when isNull item.TypeParameterList -> Some item.Identifier.ValueText
                | :? EnumDeclarationSyntax as item -> Some item.Identifier.ValueText
                | :? DelegateDeclarationSyntax as item when isNull item.TypeParameterList -> Some item.Identifier.ValueText
                | _ -> None
            name |> Option.map (fun value -> snd (sourceName node value), node.RawKind))

    let private inspectText path relative (text: string) hash bom (token: CancellationToken) =
        let root = CSharpSyntaxTree.ParseText(text, cancellationToken = token).GetRoot(token)
        let generatedSource = generatedMarker.IsMatch(root.GetLeadingTrivia().ToFullString())
        let hasCondition =
            root.DescendantTrivia(descendIntoTrivia = true)
            |> Seq.exists (fun trivia ->
                trivia.IsKind(SyntaxKind.IfDirectiveTrivia) || trivia.IsKind(SyntaxKind.ElifDirectiveTrivia)
                || trivia.IsKind(SyntaxKind.ElseDirectiveTrivia) || trivia.IsKind(SyntaxKind.EndIfDirectiveTrivia))
        let hasErrors =
            root.GetDiagnostics() |> Seq.exists (fun item -> item.Severity = DiagnosticSeverity.Error)
        let classes =
            root.DescendantNodes().OfType<ClassDeclarationSyntax>()
            |> Seq.map (fun node ->
                let ns, fullName = sourceName node node.Identifier.ValueText
                let properties =
                    node.Members.OfType<PropertyDeclarationSyntax>()
                    |> Seq.filter (fun p ->
                        p.Modifiers.Any(SyntaxKind.PublicKeyword) && not (p.Modifiers.Any(SyntaxKind.StaticKeyword)))
                    |> Seq.map (fun p ->
                        { Name = p.Identifier.ValueText
                          ColumnName = attributeValue "Column" None p.AttributeLists
                          TypeName = p.Type.ToString()
                          Declaration = p })
                    |> Seq.toArray
                { FullName = fullName; Name = node.Identifier.ValueText; Namespace = ns
                  Path = path; RelativePath = relative; Text = text; SourceHash = hash; HasUtf8Bom = bom
                  TableName = attributeValue "Table" None node.AttributeLists
                  Schema = attributeValue "Table" (Some "Schema") node.AttributeLists
                  SetName = None; Properties = properties; Declaration = node
                  GeneratedSource = generatedSource
                  CanEdit = not hasCondition && not hasErrors && isNull node.TypeParameterList })
            |> Seq.toArray
        root, classes, hasErrors

    let private genericArgument name (syntax: SyntaxNode) =
        syntax.DescendantNodesAndSelf().OfType<GenericNameSyntax>()
        |> Seq.tryFind (fun item -> item.Identifier.ValueText = name && item.TypeArgumentList.Arguments.Count = 1)
        |> Option.map (fun item -> item.TypeArgumentList.Arguments.[0].ToString().Replace("global::", ""))

    let private methodName (node: InvocationExpressionSyntax) =
        match node.Expression with
        | :? MemberAccessExpressionSyntax as access -> access.Name.Identifier.ValueText
        | :? SimpleNameSyntax as name -> name.Identifier.ValueText
        | _ -> ""

    let private getFluentMappings (classes: PocoExistingClass array) (roots: SyntaxNode array) =
        let fullNames = classes |> Array.map _.FullName |> Set.ofArray
        let shortNames =
            classes |> Array.groupBy _.Name
            |> Array.map (fun (name, items) -> name, items |> Seq.map _.FullName |> one)
            |> Map.ofArray
        let resolveClass (typeName: string) =
            if fullNames.Contains typeName then Some typeName
            elif typeName.Contains('.') then None
            else Map.tryFind (simpleName typeName) shortNames |> Option.flatten
        let sets = ResizeArray<string * string>()
        let tables = ResizeArray<string * (string * string option)>()
        let columns = ResizeArray<(string * string) * string>()
        let unsupportedTables = HashSet<string>(StringComparer.Ordinal)
        let receiver (call: InvocationExpressionSyntax) =
            match call.Expression with
            | :? MemberAccessExpressionSyntax as access -> Some access.Expression
            | _ -> None
        let receiverName (call: InvocationExpressionSyntax) =
            receiver call
            |> Option.map string
            |> Option.orElseWith (fun () ->
                if call.Expression :? SimpleNameSyntax then Some "this" else None)
        let lambdaParameter (lambda: LambdaExpressionSyntax) =
            match lambda with
            | :? SimpleLambdaExpressionSyntax as value -> Some value.Parameter.Identifier.ValueText
            | :? ParenthesizedLambdaExpressionSyntax as value when value.ParameterList.Parameters.Count = 1 ->
                Some value.ParameterList.Parameters.[0].Identifier.ValueText
            | _ -> None
        let entityFor (node: InvocationExpressionSyntax) =
            let name =
                receiver node
                |> Option.bind (fun expression ->
                    let calls = expression.DescendantNodesAndSelf().OfType<InvocationExpressionSyntax>() |> Seq.toArray
                    if calls.Length = 0 then Some (expression.ToString())
                    else calls |> Array.last |> receiverName)
                |> Option.orElseWith (fun () -> receiverName node)
            let direct = receiver node |> Option.bind (genericArgument "Entity") |> Option.bind resolveClass
            let localBuilder =
                name |> Option.bind (fun variableName ->
                    node.Ancestors().OfType<BlockSyntax>()
                    |> Seq.tryPick (fun block ->
                        block.Statements.OfType<LocalDeclarationStatementSyntax>()
                        |> Seq.collect (fun statement -> statement.Declaration.Variables)
                        |> Seq.filter (fun variable -> variable.Identifier.ValueText = variableName && variable.SpanStart < node.SpanStart && not (isNull variable.Initializer))
                        |> Seq.choose (fun variable -> genericArgument "Entity" variable.Initializer.Value)
                        |> Seq.choose resolveClass
                        |> one))
            let enclosingLambda =
                node.Ancestors().OfType<LambdaExpressionSyntax>()
                |> Seq.tryPick (fun lambda ->
                    if (lambdaParameter lambda).IsNone || lambdaParameter lambda <> name then None
                    else
                        match lambda.Parent with
                        | :? ArgumentSyntax as argument ->
                            match argument.Parent.Parent with
                            | :? InvocationExpressionSyntax as call ->
                                genericArgument "Entity" call.Expression |> Option.bind resolveClass
                            | _ -> None
                        | _ -> None)
            let configuration =
                node.Ancestors().OfType<ClassDeclarationSyntax>()
                |> Seq.tryPick (fun declaration ->
                    if isNull declaration.BaseList then None
                    elif name = Some "this" then
                        genericArgument "EntityTypeConfiguration" declaration.BaseList |> Option.bind resolveClass
                    else
                        node.Ancestors().OfType<MethodDeclarationSyntax>()
                        |> Seq.tryPick (fun method ->
                            if method.Identifier.ValueText <> "Configure" then None
                            else
                                method.ParameterList.Parameters
                                |> Seq.tryFind (fun parameter -> Some parameter.Identifier.ValueText = name && not (isNull parameter.Type))
                                |> Option.bind (fun parameter -> genericArgument "EntityTypeBuilder" parameter.Type)
                                |> Option.bind resolveClass))
            direct |> Option.orElse localBuilder |> Option.orElse enclosingLambda |> Option.orElse configuration
        for root in roots do
            for declaration in root.DescendantNodes().OfType<PropertyDeclarationSyntax>() do
                genericArgument "DbSet" declaration.Type
                |> Option.bind resolveClass
                |> Option.iter (fun name -> sets.Add(name, declaration.Identifier.ValueText))
            for call in root.DescendantNodes().OfType<InvocationExpressionSyntax>() do
                if call.ArgumentList.Arguments.Count > 0 then
                    let name = literalText call.ArgumentList.Arguments.[0].Expression
                    if methodName call = "ToTable" || methodName call = "ToView" then
                        match entityFor call, name with
                        | Some entity, Some table ->
                            let schema =
                                if call.ArgumentList.Arguments.Count < 2 then None
                                else literalText call.ArgumentList.Arguments.[1].Expression
                            tables.Add(entity, (table, schema))
                            if call.ArgumentList.Arguments.Count >= 2 && schema.IsNone
                               && not (call.ArgumentList.Arguments.[1].Expression :? LambdaExpressionSyntax) then
                                unsupportedTables.Add(entity) |> ignore
                        | Some entity, None -> unsupportedTables.Add(entity) |> ignore
                        | _ -> ()
                    elif methodName call = "HasColumnName" then
                        match receiver call, entityFor call, name with
                        | Some (:? InvocationExpressionSyntax as property), Some entity, Some column
                            when methodName property = "Property" && property.ArgumentList.Arguments.Count = 1 ->
                            match property.ArgumentList.Arguments.[0].Expression with
                            | :? LambdaExpressionSyntax as lambda ->
                                match lambda.Body with
                                | :? MemberAccessExpressionSyntax as access
                                    when lambdaParameter lambda = Some (access.Expression.ToString()) ->
                                    columns.Add((entity, access.Name.Identifier.ValueText), column)
                                | _ -> ()
                            | _ -> ()
                        | _ -> ()
        let knownMappings (items: seq<'Key * 'Value>) =
            items |> Seq.groupBy fst |> Seq.map (fun (key, entries) -> key, entries |> Seq.map snd |> one) |> Map.ofSeq
        knownMappings sets, knownMappings tables, knownMappings columns, unsupportedTables

    /// Project only the table/column metadata needed by the source SQL assistant.
    let internal ReadSourceMappings(text: string, token: CancellationToken) =
        let root, classes, hasErrors = inspectText "" "" text "" false token
        let _, tables, columns, unsupportedTables = getFluentMappings classes [| root |]
        let declaredTables =
            classes
            |> Seq.groupBy _.FullName
            |> Seq.choose (fun (name, declarations) ->
                if unsupportedTables.Contains name then Some(name, None)
                else
                    match tables |> Map.tryFind name with
                    | Some mapping -> Some(name, mapping)
                    | None ->
                        let tableDeclarations =
                            declarations |> Seq.filter (fun declaration ->
                                attributes "Table" declaration.Declaration.AttributeLists |> Seq.isEmpty |> not)
                            |> Seq.toArray
                        if tableDeclarations.Length = 0 then None
                        else
                            let values =
                                tableDeclarations |> Array.map (fun declaration ->
                                    let hasExplicitSchema =
                                        attributes "Table" declaration.Declaration.AttributeLists
                                        |> Seq.exists (fun attribute ->
                                            not (isNull attribute.ArgumentList) &&
                                            (attribute.ArgumentList.Arguments |> Seq.exists (fun argument ->
                                                (not (isNull argument.NameEquals) && argument.NameEquals.Name.Identifier.ValueText = "Schema")
                                                || (not (isNull argument.NameColon) && argument.NameColon.Name.Identifier.ValueText = "Schema"))))
                                    if hasExplicitSchema && declaration.Schema.IsNone then None
                                    else declaration.TableName |> Option.map (fun table -> table, declaration.Schema))
                            Some(name, if values |> Array.exists Option.isNone then None else values |> Array.choose id |> one))
            |> Map.ofSeq
        let sets =
            [| for context in classes do
                   for property in context.Properties do
                       let entity =
                           genericArgument "DbSet" property.Declaration.Type
                           |> Option.orElseWith (fun () -> genericArgument "IDbSet" property.Declaration.Type)
                       match entity with
                       | Some entityName -> yield context.FullName, context.Name, property.Name, entityName
                       | None -> () |]
        let properties =
            [| for entity in classes do
                   for property in entity.Properties do
                       if attributes "NotMapped" property.Declaration.AttributeLists |> Seq.isEmpty then
                           let column =
                               match columns |> Map.tryFind (entity.FullName, property.Name) with
                               | Some mapping -> mapping
                               | None ->
                                   if property.ColumnName.IsNone &&
                                      (attributes "Column" property.Declaration.AttributeLists |> Seq.isEmpty |> not) then None
                                   else Some(defaultArg property.ColumnName property.Name)
                           yield entity.FullName, property.Name, column |]
        classes |> Array.map (fun item -> item.FullName, item.Name) |> Array.distinct, sets, declaredTables, properties, hasErrors

    let private ignoredDirectories =
        HashSet<string>([| ".git"; ".vs"; "obj"; "bin"; "node_modules"; "packages" |], StringComparer.OrdinalIgnoreCase)

    let private sourcePaths root (token: CancellationToken) =
        seq {
            let pending = Stack<string>()
            pending.Push(root)
            let options = EnumerationOptions(AttributesToSkip = FileAttributes.ReparsePoint, IgnoreInaccessible = false)
            while pending.Count > 0 do
                token.ThrowIfCancellationRequested()
                let folder = pending.Pop()
                yield! Directory.EnumerateFiles(folder, "*.cs", options)
                for child in Directory.EnumerateDirectories(folder, "*", options) do
                    if not (ignoredDirectories.Contains(Path.GetFileName(child))) then pending.Push(child)
        }

    let private projectPathKey (path: string) =
        let normalized = path.Replace('\\', '/')
        (if normalized.StartsWith("./", StringComparison.Ordinal) then normalized.Substring(2) else normalized).ToUpperInvariant()

    let private findProjects (path: string) (token: CancellationToken) =
        let input = Path.GetFullPath path
        let rec nearest (folder: DirectoryInfo) =
            token.ThrowIfCancellationRequested()
            if isNull folder then [||]
            elif not folder.Exists then nearest folder.Parent
            else
                let options = EnumerationOptions(AttributesToSkip = FileAttributes.ReparsePoint, IgnoreInaccessible = true)
                match folder.EnumerateFiles("*.csproj", options) |> Seq.truncate 2 |> Seq.map _.FullName |> Seq.toArray with
                | [||] -> nearest folder.Parent
                | projects -> projects
        if File.Exists input && String.Equals(Path.GetExtension input, ".csproj", StringComparison.OrdinalIgnoreCase) then
            [| input |]
        else
            let folder = if File.Exists input then Path.GetDirectoryName input else input
            nearest (DirectoryInfo folder)

    /// Find one unambiguous nearest project, including an output folder not created yet.
    let FindProject(path: string, token: CancellationToken) =
        match findProjects path token with
        | [| project |] -> Some project
        | _ -> None

    let NullableSyntaxForProject(projectFile: string option) =
        projectFile |> Option.bind (fun path ->
            if not (File.Exists path) || FileInfo(path).Length > 1048576L then None
            else
                let project = XDocument.Load(path)
                let properties name = project.Descendants() |> Seq.filter (fun node -> node.Name.LocalName = name)
                let version (node: XElement) =
                    let mutable value = LanguageVersion.Default
                    if LanguageVersionFacts.TryParse(node.Value.Trim(), &value) then
                        Some(CSharpParseOptions(value).LanguageVersion >= LanguageVersion.CSharp8)
                    else None
                let languages = properties "LangVersion" |> Seq.toArray
                if languages |> Array.exists (fun node -> version node = Some false) then Some false
                elif languages |> Array.exists (fun node ->
                    version node = Some true
                    && (node.AncestorsAndSelf() |> Seq.forall (fun element -> isNull (element.Attribute(XName.Get "Condition"))))) then Some true
                else
                    let targets =
                        Seq.append (properties "TargetFramework") (properties "TargetFrameworks")
                        |> Seq.collect (fun node -> node.Value.Split(';', StringSplitOptions.TrimEntries ||| StringSplitOptions.RemoveEmptyEntries))
                        |> Seq.toArray
                    let legacyFramework =
                        properties "TargetFrameworkVersion" |> Seq.exists (fun node ->
                            Regex.IsMatch(node.Value.Trim(), @"^[vV]4\.\d+(?:\.\d+)?$"))
                    let legacyTarget = targets |> Array.exists (fun tfm ->
                        Regex.IsMatch(tfm, @"^net(?:4[0-9]{1,2}|(?:coreapp[12]|standard[12])\.\d+)$", RegexOptions.IgnoreCase)
                        && not (tfm.Equals("netstandard2.1", StringComparison.OrdinalIgnoreCase)))
                    if legacyFramework || legacyTarget then Some false
                    elif targets.Length > 0 && (targets |> Array.forall (fun tfm ->
                        Regex.IsMatch(tfm, @"^net(?:(?:[5-9]|[1-9]\d+)\.\d+(?:-|$)|coreapp3\.\d+$|standard2\.1$)", RegexOptions.IgnoreCase))) then Some true
                    else None)

    let private projectInfo path (warnings: ResizeArray<string>) (token: CancellationToken) =
        let projects =
            findProjects path token
        match projects with
        | [| project |] when FileInfo(project).Length <= 1048576L ->
            let xml = XDocument.Load(project)
            let packages =
                xml.Descendants()
                |> Seq.filter (fun item ->
                    item.Name.LocalName = "PackageReference" || item.Name.LocalName = "Reference")
                |> Seq.choose (fun item ->
                    let attribute = item.Attribute(XName.Get("Include"))
                    if isNull attribute then None else Some (attribute.Value.Split(',').[0].Trim()))
                |> Seq.toArray
            let ef6 = packages |> Array.exists (fun package -> package.Equals("EntityFramework", StringComparison.OrdinalIgnoreCase))
            let core = packages |> Array.exists (fun package ->
                package.Equals("Microsoft.EntityFrameworkCore", StringComparison.OrdinalIgnoreCase)
                || package.StartsWith("Microsoft.EntityFrameworkCore.", StringComparison.OrdinalIgnoreCase))
            if ef6 && core then warnings.Add("The project references both EF6 and EF Core. Choose the target explicitly.")
            let targets =
                [| if ef6 then PocoTarget.Ef6
                   if core then PocoTarget.EfCore |]
            let readProperty name =
                xml.Descendants() |> Seq.filter (fun item -> item.Name.LocalName = name) |> Seq.map (fun item -> item.Value.Trim())
                |> Seq.filter (String.IsNullOrWhiteSpace >> not) |> one
            let nullable =
                match readProperty "Nullable" with
                | Some ("enable" | "annotations") -> Some true
                | Some ("disable" | "warnings") -> Some false
                | _ -> None
            let compile = xml.Descendants() |> Seq.filter (fun item -> item.Name.LocalName = "Compile") |> Seq.toArray
            if compile |> Array.exists (fun item ->
                not (isNull (item.Attribute(XName.Get("Include"))))
                || not (isNull (item.Attribute(XName.Get("Remove"))))) then
                warnings.Add("The project contains explicit Compile rules. The scan covers the selected directory and may include files outside the build.")
            let generatedFiles =
                compile |> Seq.choose (fun item ->
                    let child name = item.Elements() |> Seq.tryFind (fun child -> child.Name.LocalName = name)
                    match child "AutoGen", child "DependentUpon" with
                    | Some autoGen, Some dependency
                        when autoGen.Value.Trim().Equals("true", StringComparison.OrdinalIgnoreCase)
                             && not (String.IsNullOrWhiteSpace dependency.Value) ->
                        [ "Update"; "Include" ]
                        |> List.tryPick (fun name ->
                            let attribute = item.Attribute(XName.Get name)
                            if isNull attribute then None else Some(projectPathKey attribute.Value))
                    | _ -> None)
                |> Set.ofSeq
            targets, readProperty "RootNamespace", nullable, Some(project, generatedFiles)
        | _ ->
            if projects.Length > 1 then warnings.Add("Several projects are in the nearest project folder. Select a .csproj to detect its EF version.")
            [||], None, None, None

    let private contextCandidates (classes: PocoExistingClass array) =
        let contexts =
            classes |> Array.filter (fun item ->
                let declaration = item.Declaration
                not (isNull declaration.BaseList) && isNull declaration.TypeParameterList
                && not (declaration.Modifiers.Any(SyntaxKind.AbstractKeyword))
                && (declaration.Parent :? BaseNamespaceDeclarationSyntax || declaration.Parent :? CompilationUnitSyntax)
                && (declaration.BaseList.Types |> Seq.exists (fun baseType -> simpleName (baseType.Type.ToString()) = "DbContext")))
        let isModelContext (item: PocoExistingClass) =
            (item.Properties |> Array.exists (fun property -> genericArgument "DbSet" property.Declaration.Type |> Option.isSome))
            || (item.Declaration.Members.OfType<MethodDeclarationSyntax>()
                |> Seq.exists (fun methodNode ->
                    methodNode.Identifier.ValueText = "OnModelCreating" && methodNode.Modifiers.Any(SyntaxKind.OverrideKeyword)))
        let mapped = contexts |> Array.filter isModelContext
        let candidates = if mapped.Length > 0 then mapped else contexts
        let original =
            candidates |> Array.filter (fun item ->
                not (item.Text.StartsWith("// <auto-generated by AnotherEdit>", StringComparison.Ordinal)))
        (if original.Length > 0 then original else candidates) |> Array.distinctBy _.FullName

    let private frameworkFromSource (contexts: PocoExistingClass array) =
        let version (name: string) =
            let name = name.Replace("global::", "")
            match name with
            | "Microsoft.EntityFrameworkCore" | "Microsoft.EntityFrameworkCore.DbContext" -> Some PocoTarget.EfCore
            | "System.Data.Entity" | "System.Data.Entity.DbContext" -> Some PocoTarget.Ef6
            | _ -> None
        contexts
        |> Seq.collect (fun context ->
            let baseTypes = context.Declaration.BaseList.Types |> Seq.map (fun item -> item.Type.ToString())
            let imports =
                context.Declaration.SyntaxTree.GetRoot().DescendantNodes().OfType<UsingDirectiveSyntax>()
                |> Seq.choose (fun directive -> if isNull directive.Name then None else Some (directive.Name.ToString()))
            Seq.append baseTypes imports)
        |> Seq.choose version
        |> one

    let private analyzeSources
        (root: string, projectGeneratedFiles: (string * Set<string>) option,
         targets: PocoTarget array, projectNamespace: string option, nullable: bool option,
         sources: PocoExistingSource array, warnings: ResizeArray<string>, token: CancellationToken) : PocoExistingScan =
        let roots = ResizeArray<SyntaxNode>()
        let declared = ResizeArray<string * (string * int)>()
        let parsed = ResizeArray<PocoExistingClass>()
        for source in sources do
            token.ThrowIfCancellationRequested()
            let syntax, classes, bad = inspectText source.Path source.RelativePath source.Text source.SourceHash source.HasUtf8Bom token
            if bad then warnings.Add(source.RelativePath + " has C# syntax errors and is protected from updates.")
            roots.Add(syntax)
            for name, kind in TypeDeclarations syntax do declared.Add(name, (source.RelativePath, kind))
            parsed.AddRange(classes)
        let classes = parsed.ToArray() |> Array.sortBy (fun item -> item.FullName, item.RelativePath)
        let sets, tables, columns, _ = getFluentMappings classes (roots.ToArray())
        let mapped =
            classes
            |> Array.map (fun item ->
                let fluent = tables |> Map.tryFind item.FullName
                let table, schema =
                    match fluent with
                    | Some (Some (name, schema)) -> Some name, schema
                    | _ -> item.TableName, item.Schema
                let properties =
                    item.Properties |> Array.map (fun property ->
                        match Map.tryFind (item.FullName, property.Name) columns with
                        | Some (Some name) -> { property with ColumnName = Some name }
                        | _ -> property)
                let ambiguousColumn =
                    item.Properties |> Array.exists (fun property ->
                        Map.tryFind (item.FullName, property.Name) columns = Some None)
                let generatedSource =
                    item.GeneratedSource && (projectGeneratedFiles |> Option.forall (fun (project, generatedFiles) ->
                        Set.contains (projectPathKey (Path.GetRelativePath(Path.GetDirectoryName project, item.Path))) generatedFiles))
                { item with TableName = table; Schema = schema; Properties = properties; GeneratedSource = generatedSource
                            SetName = sets |> Map.tryFind item.FullName |> Option.flatten
                            CanEdit = item.CanEdit && fluent <> Some None && not ambiguousColumn })
        for KeyValue(name, value) in tables do
            if value.IsNone then warnings.Add(name + " has conflicting table mappings. Existing code is protected.")
        for KeyValue((name, property), value) in columns do
            if value.IsNone then warnings.Add(name + "." + property + " has conflicting column mappings. Existing code is protected.")
        let conflicts = HashSet<string>(StringComparer.Ordinal)
        let declaredTypes =
            declared |> Seq.groupBy fst |> Seq.map (fun (name, entries) ->
                let files, kinds = entries |> Seq.map snd |> Seq.toArray |> Array.unzip
                if (Array.distinct kinds).Length > 1 then
                    conflicts.Add(name) |> ignore
                    warnings.Add(name + " has conflicting type declarations in " + String.Join(", ", Array.distinct files) + ".")
                name, files)
            |> Map.ofSeq
        let contexts = mapped |> Array.filter (fun item -> not (conflicts.Contains item.FullName)) |> contextCandidates
        let context = if contexts.Length = 1 then Some contexts.[0] else None
        let target = if targets.Length = 0 then frameworkFromSource contexts else one targets
        let modelNamespaces =
            mapped |> Seq.filter (fun item -> item.TableName.IsSome || item.SetName.IsSome)
            |> Seq.map _.Namespace |> Seq.filter (String.IsNullOrWhiteSpace >> not) |> one
        let sourceNamespace =
            mapped |> Seq.map _.Namespace |> Seq.filter (String.IsNullOrWhiteSpace >> not) |> one
        let inferredNaming pick =
            mapped
            |> Seq.choose (fun item ->
                match item.TableName |> Option.orElse item.SetName, pick item with
                | Some table, Some name ->
                    if name = table then Some PocoNaming.AsInDatabase
                    elif table = name + "s" || table = name + "es" then Some PocoNaming.Singular
                    elif name = table + "s" || name = table + "es" then Some PocoNaming.Plural
                    else None
                | _ -> None)
            |> one
        { Root = root; ProjectFile = projectGeneratedFiles |> Option.map fst
          Classes = mapped; Files = sources; DeclaredTypes = declaredTypes; Target = target
          Namespace = context |> Option.map _.Namespace |> Option.orElse modelNamespaces
                      |> Option.orElse sourceNamespace |> Option.orElse projectNamespace |> Option.defaultValue ""
          ContextName = context |> Option.map _.Name |> Option.defaultValue ""
          ContextCandidates = contexts |> Array.map _.FullName
          NullableReferenceTypes = nullable
          ClassNaming = inferredNaming (fun item -> Some item.Name)
          SetNaming = inferredNaming _.SetName; Warnings = warnings.ToArray() }

    let Scan (path: string, token: CancellationToken) : PocoExistingScan =
        let input = Path.GetFullPath(path)
        let directory = Directory.Exists(input)
        if not directory && not (File.Exists(input)) then invalidArg (nameof path) "Choose an existing C# folder or project."
        if (File.GetAttributes(input) &&& FileAttributes.ReparsePoint) <> enum<FileAttributes> 0 then
            invalidArg (nameof path) "Choose a folder or project that is not a filesystem link."
        let extension = Path.GetExtension(input)
        let isSource = not directory && extension.Equals(".cs", StringComparison.OrdinalIgnoreCase)
        if not directory && not isSource && not (extension.Equals(".csproj", StringComparison.OrdinalIgnoreCase)) then
            invalidArg (nameof path) "Choose a C# file, project, or folder."
        let root = if directory then input else Path.GetDirectoryName(input)
        let warnings = ResizeArray<string>()
        let targets, projectNamespace, nullable, projectGeneratedFiles = projectInfo input warnings token
        let sources = ResizeArray<PocoExistingSource>()
        let files = (if isSource then Seq.singleton input else sourcePaths root token) |> Seq.truncate 1001 |> Seq.toArray
        if files.Length > 1000 then invalidOp "The C# scan exceeded 1,000 files. Select a smaller model folder."
        let mutable totalBytes = 0L
        for file in files do
            token.ThrowIfCancellationRequested()
            let relative = Path.GetRelativePath(root, file)
            try
                use stream = new FileStream(file, FileMode.Open, FileAccess.Read, FileShare.Read)
                let length = stream.Length
                if length > 2097152L then warnings.Add(relative + " exceeds the 2 MiB source-file limit and was skipped.")
                else
                    totalBytes <- totalBytes + length
                    if totalBytes > 33554432L then invalidOp "The C# scan exceeded 32 MiB. Select a smaller model folder."
                    let bytes = Array.zeroCreate<byte> (int length)
                    stream.ReadExactly(bytes)
                    let bom = bytes.Length >= 3 && bytes.[0] = 239uy && bytes.[1] = 187uy && bytes.[2] = 191uy
                    let offset = if bom then 3 else 0
                    let text = utf8.GetString(bytes, offset, bytes.Length - offset)
                    if text.IndexOf('\000') >= 0 then warnings.Add(relative + " is not UTF-8 C# and was skipped.")
                    else
                        let hash = Convert.ToHexString(SHA256.HashData(bytes))
                        sources.Add { Path = file; RelativePath = relative; Text = text; SourceHash = hash; HasUtf8Bom = bom }
            with :? DecoderFallbackException ->
                warnings.Add(relative + " is not UTF-8 C# and was skipped.")
        analyzeSources(root, projectGeneratedFiles, targets, projectNamespace, nullable, sources.ToArray(), warnings, token)

    /// Infer only an unambiguous model provider. Connection strings are neither
    /// returned nor rewritten; ambiguous/multi-provider projects keep the picker.
    let DetectProvider(scan: PocoExistingScan, token: CancellationToken) : (string * string) option =
        token.ThrowIfCancellationRequested()
        let unique (values: seq<string>) evidence =
            match values |> Seq.distinct |> Seq.toArray with
            | [| provider |] -> Some(provider, evidence)
            | _ -> None
        let calls =
            Map.ofList [ "UseSqlServer", "sqlserver"; "UseSqlite", "sqlite"; "UseNpgsql", "postgresql"
                         "UseMySql", "mysql"; "UseMySQL", "mysql"; "UseMariaDb", "mariadb"
                         "UseOracle", "oracle"; "UseDb2", "db2"; "UseDB2", "db2"; "UseJet", "oledb" ]
        let sourceProviders =
            scan.Files |> Array.collect (fun source ->
                token.ThrowIfCancellationRequested()
                CSharpSyntaxTree.ParseText(source.Text, cancellationToken = token).GetRoot(token)
                    .DescendantNodes().OfType<InvocationExpressionSyntax>()
                |> Seq.choose (fun call -> Map.tryFind (methodName call) calls) |> Seq.toArray)
            |> Array.distinct
        let invariant (name: string) =
            match name.Trim().ToLowerInvariant() with
            | "system.data.sqlclient" | "microsoft.data.sqlclient" -> Some "sqlserver"
            | "system.data.sqlite" | "system.data.sqlite.ef6" | "microsoft.data.sqlite" -> Some "sqlite"
            | "npgsql" -> Some "postgresql"
            | "mysql.data.mysqlclient" | "mysqlconnector" -> Some "mysql"
            | "oracle.manageddataaccess.client" | "oracle.dataaccess.client" -> Some "oracle"
            | "ibm.data.db2" | "ibm.data.db2.core" -> Some "db2"
            | "system.data.oledb" -> Some "oledb"
            | _ -> None
        let readXml path =
            token.ThrowIfCancellationRequested()
            try
                if File.Exists path && FileInfo(path).Length <= 4L * 1024L * 1024L then
                    let settings = System.Xml.XmlReaderSettings(DtdProcessing = System.Xml.DtdProcessing.Prohibit, XmlResolver = null)
                    use reader = System.Xml.XmlReader.Create(path, settings)
                    Some(XDocument.Load reader)
                else None
            with :? IOException | :? UnauthorizedAccessException | :? System.Xml.XmlException -> None
        let configurationProviders =
            seq {
                for folder in [| scan.Root; scan.ProjectFile |> Option.map Path.GetDirectoryName |> Option.defaultValue scan.Root |] |> Array.distinct do
                    for file in [| "App.config"; "app.config"; "Web.config"; "web.config" |] do
                        match readXml (Path.Combine(folder, file)) with
                        | Some xml ->
                            for element in xml.Descendants() do
                                for name in [| "providerName"; "invariantName" |] do
                                    let attribute = element.Attribute(XName.Get name)
                                    if not (isNull attribute) then yield! invariant attribute.Value |> Option.toArray
                        | None -> ()
            } |> Seq.distinct |> Seq.toArray
        let packageProviders =
            match scan.ProjectFile |> Option.bind readXml with
            | None -> [||]
            | Some xml ->
                xml.Descendants()
                |> Seq.filter (fun element -> element.Name.LocalName = "PackageReference" || element.Name.LocalName = "Reference")
                |> Seq.choose (fun element ->
                    let includeName = element.Attribute(XName.Get "Include")
                    if isNull includeName then None
                    else
                        match includeName.Value.Split(',').[0].Trim().ToLowerInvariant() with
                        | "microsoft.entityframeworkcore.sqlserver" | "entityframework.sqlserver" -> Some "sqlserver"
                        | "microsoft.entityframeworkcore.sqlite" | "system.data.sqlite.ef6" -> Some "sqlite"
                        | "npgsql.entityframeworkcore.postgresql" | "entityframework6.npgsql" -> Some "postgresql"
                        | "pomelo.entityframeworkcore.mysql" | "mysql.entityframeworkcore" | "mysql.data.entityframework" -> Some "mysql"
                        | "oracle.entityframeworkcore" | "oracle.manageddataaccess.entityframework" -> Some "oracle"
                        | "ibm.entityframeworkcore" | "ibm.entityframeworkcore-lnx" -> Some "db2"
                        | "entityframeworkcore.jet" -> Some "oledb"
                        | _ -> None)
                |> Seq.distinct |> Seq.toArray
        if sourceProviders.Length > 0 then unique sourceProviders "Detected from the model's provider configuration."
        elif configurationProviders.Length > 0 then unique configurationProviders "Detected from the project's provider configuration."
        else unique packageProviders "Detected from the project's EF provider reference."

    let private isLink path =
        let mutable current = if Directory.Exists path then DirectoryInfo path else DirectoryInfo(Path.GetDirectoryName path)
        let mutable linked = false
        while not (isNull current) && not linked do
            if current.Exists && current.Attributes.HasFlag(FileAttributes.ReparsePoint) then linked <- true
            current <- current.Parent
        linked || (File.Exists path && File.GetAttributes(path).HasFlag(FileAttributes.ReparsePoint))

    let private readProjectReferences project =
        use stream = File.OpenRead project
        if stream.Length > 1048576L then None
        else
            use reader = XmlReader.Create(stream, XmlReaderSettings(DtdProcessing = DtdProcessing.Prohibit, XmlResolver = null))
            XDocument.Load(reader).Descendants()
            |> Seq.filter (fun node -> node.Name.LocalName = "ProjectReference")
            |> Seq.choose (fun node ->
                let includePath = node.Attribute(XName.Get "Include")
                if isNull includePath then None
                else PocoProjectIntegration.localPath (Path.GetDirectoryName project) includePath.Value)
            |> Some

    let private solutionProjectLine =
        Regex("^\\s*Project\\(\"[^\"]+\"\\)\\s*=\\s*\"[^\"]*\",\\s*\"([^\"]+\\.csproj)\",", RegexOptions.IgnoreCase)

    /// Suggest a consumer only when one nearby C# project directly references the model.
    let FindConsumerProject(scan: PocoExistingScan, token: CancellationToken) : string option =
        token.ThrowIfCancellationRequested()
        scan.ProjectFile |> Option.bind (fun sourceProject ->
            let sourceProject = Path.GetFullPath sourceProject
            let sourceFolder = DirectoryInfo(Path.GetDirectoryName sourceProject)
            let samePath left right = String.Equals(left, right, StringComparison.OrdinalIgnoreCase)
            let within folder path =
                let relative = Path.GetRelativePath(folder, path)
                not (Path.IsPathRooted relative || relative = ".." || relative.StartsWith(".." + string Path.DirectorySeparatorChar, StringComparison.Ordinal))
            let options = EnumerationOptions(AttributesToSkip = FileAttributes.ReparsePoint, IgnoreInaccessible = false)
            let bounded limit items =
                let found = items |> Seq.truncate (limit + 1) |> Seq.toArray
                if found.Length > limit then invalidOp "The nearby project search exceeded its limit."
                found
            let repositoryRoot (folder: DirectoryInfo) =
                let marker = Path.Combine(folder.FullName, ".git")
                Directory.Exists marker || File.Exists marker
            let solutionProjects (solution: FileInfo) =
                token.ThrowIfCancellationRequested()
                use stream = solution.OpenRead()
                if stream.Length > 1048576L then invalidOp "The nearby solution exceeded the 1 MiB limit."
                use reader = new StreamReader(stream)
                Seq.unfold (fun () -> Option.ofObj (reader.ReadLine()) |> Option.map (fun line -> line, ())) ()
                |> Seq.choose (fun line ->
                    token.ThrowIfCancellationRequested()
                    let entry = solutionProjectLine.Match(line)
                    if entry.Success then
                        PocoProjectIntegration.localPath solution.DirectoryName entry.Groups.[1].Value
                    else None)
                |> bounded 128
            let rec findSolution depth (folder: DirectoryInfo) =
                token.ThrowIfCancellationRequested()
                if depth = 4 || isNull folder || isNull folder.Parent then None
                else
                    let projects =
                        folder.EnumerateFiles("*.sln", options) |> bounded 16
                        |> Array.map solutionProjects
                        |> Array.filter (Array.exists (samePath sourceProject))
                    let local =
                        if projects.Length = 0 then None
                        else Some(Array.concat projects |> Array.filter (within folder.FullName))
                    let parent = if repositoryRoot folder then None else findSolution (depth + 1) folder.Parent
                    match local, parent with
                    | Some current, Some above -> Some(Array.append current above)
                    | _ -> local |> Option.orElse parent
            let rec nearbyFolders depth (folder: DirectoryInfo) =
                seq {
                    token.ThrowIfCancellationRequested()
                    yield folder
                    if depth < 2 then
                        for child in folder.EnumerateDirectories("*", options) do
                            token.ThrowIfCancellationRequested()
                            if not (ignoredDirectories.Contains child.Name || repositoryRoot child) then
                                yield! nearbyFolders (depth + 1) child
                }
            let nearbyProjects () =
                if isNull sourceFolder.Parent || isNull sourceFolder.Parent.Parent || repositoryRoot sourceFolder then [||]
                else
                    nearbyFolders 0 sourceFolder.Parent |> bounded 128
                    |> Seq.collect (fun folder ->
                        token.ThrowIfCancellationRequested()
                        folder.EnumerateFiles("*.csproj", options) |> Seq.map _.FullName)
                    |> bounded 128
            try
                if not (File.Exists sourceProject) || isLink sourceProject then None
                else
                    let candidates =
                        findSolution 0 sourceFolder |> Option.defaultWith nearbyProjects
                        |> Array.distinctBy projectPathKey
                        |> bounded 128
                    let consumers =
                        candidates |> Seq.filter (fun project ->
                            token.ThrowIfCancellationRequested()
                            if samePath project sourceProject || not (File.Exists project) || isLink project then false
                            else
                                match readProjectReferences project with
                                | Some references -> references |> Seq.exists (samePath sourceProject)
                                | None -> invalidOp "A nearby project exceeded the 1 MiB limit.")
                        |> Seq.truncate 2 |> Seq.toArray
                    match consumers with
                    | [| consumer |] ->
                        let folder = Path.GetDirectoryName consumer
                        if within sourceFolder.FullName folder || within scan.Root folder then None
                        else FindProject(folder, token) |> Option.filter (samePath consumer)
                    | _ -> None
            with
            | :? IOException | :? UnauthorizedAccessException | :? ArgumentException
            | :? InvalidOperationException | :? XmlException -> None)

    /// Locate the model library behind an output folder in a consuming application.
    /// Explicit source/project selections remain authoritative; folder discovery follows
    /// local ProjectReferences before considering a context generated into the app.
    let FindModel(path: string, token: CancellationToken) : PocoExistingScan option =
        let input = Path.GetFullPath path
        let explicitSource = File.Exists input &&
                             (Path.GetExtension(input).Equals(".csproj", StringComparison.OrdinalIgnoreCase)
                              || Path.GetExtension(input).Equals(".cs", StringComparison.OrdinalIgnoreCase))
        let usable (scan: PocoExistingScan) = scan.ContextCandidates.Length = 1 && scan.Target.IsSome
        let tryScan candidate =
            token.ThrowIfCancellationRequested()
            try Some(Scan(candidate, token))
            with
            | :? OperationCanceledException -> reraise()
            | :? IOException | :? UnauthorizedAccessException | :? ArgumentException | :? InvalidOperationException -> None
        let explicitScan = if explicitSource then tryScan input else None
        let originalModel = explicitScan |> Option.exists (fun scan ->
            usable scan && (contextCandidates scan.Classes |> Array.exists (fun context ->
                not (context.Text.StartsWith("// <auto-generated by AnotherEdit>", StringComparison.Ordinal)))))
        if originalModel then explicitScan
        elif File.Exists input && Path.GetExtension(input).Equals(".cs", StringComparison.OrdinalIgnoreCase) then explicitScan
        else
            let seen = HashSet<string>(StringComparer.OrdinalIgnoreCase)
            let mutable visited = 0
            let rec discover depth project =
                token.ThrowIfCancellationRequested()
                if depth > 8 || visited >= 32 || not (File.Exists project) || isLink project || not (seen.Add project) then None
                else
                    visited <- visited + 1
                    let references =
                        try readProjectReferences project |> Option.defaultValue Seq.empty |> Seq.truncate 32 |> Seq.toArray
                        with :? XmlException -> [||]
                    match references |> Array.tryPick (discover (depth + 1)) with
                    | Some model -> Some model
                    | None -> tryScan project |> Option.filter usable
            match FindProject(input, token) |> Option.bind (discover 0) with
            | Some model -> Some model
            | None ->
                explicitScan
                |> Option.orElseWith (fun () -> FindProject(input, token) |> Option.bind tryScan)
                |> Option.orElseWith (fun () -> if Directory.Exists input then tryScan input else None)

    let private key (item: SqlCatalogObject) = item.Kind, item.Schema, item.Name

    let private objectMatches (scan: PocoExistingScan, items: SqlCatalogObject array) =
        let objects = items |> Array.filter (fun item ->
            item.Kind = SqlCatalogObjectKind.Table || item.Kind = SqlCatalogObjectKind.View)
        let scopes = objects |> Array.countBy _.Name |> Map.ofArray
        let byName names =
            scan.Classes
            |> Array.collect (fun item -> names item |> Array.distinct |> Array.map (fun name -> name, item))
            |> Array.groupBy fst
            |> Array.map (fun (name, group) -> name, group |> Array.map snd)
            |> Map.ofArray
        let explicit = byName (fun item -> item.TableName |> Option.toArray)
        let conventions = byName (fun item ->
            if item.TableName.IsSome then [||]
            else Array.append [| item.Name |] (item.SetName |> Option.toArray))
        let candidates (item: SqlCatalogObject) =
            let uniqueName = scopes.[item.Name] = 1
            let exact =
                defaultArg (Map.tryFind item.Name explicit) [||]
                |> Array.filter (fun existing -> existing.Schema.IsNone || existing.Schema = Some item.Schema)
            if exact.Length > 0 then
                exact, (not uniqueName && (exact |> Array.exists (fun existing -> existing.Schema.IsNone)))
            else defaultArg (Map.tryFind item.Name conventions) [||], not uniqueName
        let candidateMap =
            objects |> Array.map (fun item -> key item, candidates item)
        let singles =
            candidateMap
            |> Array.choose (function objectKey, ([| existing |], false) -> Some (objectKey, existing) | _ -> None)
            |> Array.groupBy (fun (_, existing) -> existing.FullName)
        let matches =
            singles
            |> Array.choose (function _, [| association |] -> Some association | _ -> None)
            |> Map.ofArray
        let ambiguous =
            candidateMap
            |> Array.choose (fun (objectKey, (existing, _)) ->
                if existing.Length > 0 && not (matches.ContainsKey(objectKey)) then Some objectKey else None)
            |> Set.ofArray
        matches, ambiguous

    let Matches (scan: PocoExistingScan, items: SqlCatalogObject array) = objectMatches (scan, items) |> fst

    let AmbiguousMatches (scan: PocoExistingScan, items: SqlCatalogObject array) = objectMatches (scan, items) |> snd

    let Overrides (scan: PocoExistingScan, items: SqlCatalogObject array) =
        Matches(scan, items)
        |> Map.map (fun _ existing ->
            let props =
                existing.Properties
                |> Seq.filter (fun property ->
                    attributes "NotMapped" property.Declaration.AttributeLists |> Seq.isEmpty)
                |> Seq.groupBy (fun property -> defaultArg property.ColumnName property.Name)
                |> Seq.choose (fun (column, matches) -> matches |> Seq.map _.Name |> one |> Option.map (fun name -> column, name))
                |> Map.ofSeq
            { ClassName = existing.Name; SetName = defaultArg existing.SetName ""; Properties = props })

    let private clrNames =
        [ "Boolean", "bool"; "Byte", "byte"; "SByte", "sbyte"; "Int16", "short"; "UInt16", "ushort"
          "Int32", "int"; "UInt32", "uint"; "Int64", "long"; "UInt64", "ulong"; "Single", "float"
          "Double", "double"; "Decimal", "decimal"; "Char", "char"; "String", "string"; "Object", "object" ]
        |> List.map (fun (systemName, csharp) -> "System." + systemName, csharp)
        |> Map.ofList

    let private typeName (syntax: TypeSyntax) =
        let value = syntax.ToString().Replace("global::", "")
        defaultArg (Map.tryFind value clrNames) value

    let rec private canonicalType (syntax: TypeSyntax) =
        match syntax with
        | :? NullableTypeSyntax as nullable -> canonicalType nullable.ElementType + "?"
        | :? ArrayTypeSyntax as array -> canonicalType array.ElementType + String.Concat(array.RankSpecifiers |> Seq.map string)
        | _ -> typeName syntax

    let private autoProperty (property: PocoExistingProperty) =
        let declaration = property.Declaration
        not (isNull declaration.AccessorList) && isNull declaration.ExpressionBody && isNull declaration.Initializer
        && not (declaration.Modifiers.Any(SyntaxKind.OverrideKeyword) || declaration.Modifiers.Any(SyntaxKind.AbstractKeyword))
        && declaration.AccessorList.Accessors.Count = 2
        && (declaration.AccessorList.Accessors |> Seq.forall (fun accessor ->
            isNull accessor.Body && isNull accessor.ExpressionBody && accessor.SemicolonToken.IsKind(SyntaxKind.SemicolonToken)))

    let private lineStart (text: string) position =
        if position = 0 then 0 else text.LastIndexOf('\n', position - 1) + 1

    let private lineIndent (text: string) position =
        let start = lineStart text position
        let prefix = text.Substring(start, position - start)
        if prefix |> Seq.forall (fun c -> c = ' ' || c = '\t') then Some prefix else None

    let private indentation (item: PocoExistingClass) =
        lineIndent item.Text item.Declaration.SpanStart
        |> Option.bind (fun prefix ->
            item.Declaration.Members
            |> Seq.choose (fun memberNode -> lineIndent item.Text memberNode.SpanStart)
            |> Seq.choose (fun indent ->
                if indent.Length > prefix.Length && indent.StartsWith(prefix, StringComparison.Ordinal) then
                    Some(indent.Substring(prefix.Length))
                else None)
            |> one)

    let private lineEnding (text: string) =
        let position = text.IndexOf('\n')
        if position < 0 then None
        elif position > 0 && text.[position - 1] = '\r' then Some "\r\n"
        else Some "\n"

    /// Match the layout of generated C# to the concrete context or mapped model source.
    /// Existing architecture, declaration names and generated code stay intact.
    let FormatGenerated(scan: PocoExistingScan, generation: PocoGeneration, token: CancellationToken) =
        let context =
            scan.Classes |> Array.filter (fun item ->
                item.Name = scan.ContextName && item.Namespace = scan.Namespace)
        let mapped = scan.Classes |> Array.filter (fun item -> item.TableName.IsSome || item.SetName.IsSome)
        let reference =
            if context.Length > 0 then context
            elif mapped.Length > 0 then mapped
            else scan.Classes
        let fileScoped =
            reference
            |> Seq.choose (fun item ->
                item.Declaration.Ancestors().OfType<BaseNamespaceDeclarationSyntax>()
                |> Seq.tryHead |> Option.map (fun node -> node :? FileScopedNamespaceDeclarationSyntax))
            |> one |> Option.defaultValue false
        let indent = reference |> Seq.choose indentation |> one |> Option.defaultValue "    "
        let newline =
            reference |> Seq.distinctBy _.Path |> Seq.choose (fun item -> lineEnding item.Text)
            |> one |> Option.defaultValue Environment.NewLine
        let format (file: PocoGeneratedFile) =
            token.ThrowIfCancellationRequested()
            if not (file.FileName.EndsWith(".cs", StringComparison.OrdinalIgnoreCase)) then file
            elif not fileScoped && indent = "    " && lineEnding file.Text = Some newline then file
            else
                let original = CSharpSyntaxTree.ParseText(file.Text, cancellationToken = token).GetCompilationUnitRoot(token)
                if original.ContainsDiagnostics then file
                else
                    let formatted =
                        match original.Members |> Seq.toArray with
                        | [| :? NamespaceDeclarationSyntax as block |] when fileScoped ->
                            let scoped =
                                SyntaxFactory.FileScopedNamespaceDeclaration(block.Name)
                                    .WithNamespaceKeyword(block.NamespaceKeyword).WithExterns(block.Externs)
                                    .WithUsings(block.Usings).WithMembers(block.Members)
                            original.WithMembers(SyntaxFactory.SingletonList<MemberDeclarationSyntax>(scoped))
                        | _ -> original
                    let text = formatted.NormalizeWhitespace(indent, newline, false).ToFullString() + newline
                    let verified = CSharpSyntaxTree.ParseText(text, cancellationToken = token).GetCompilationUnitRoot(token)
                    if verified.ContainsDiagnostics || not (SyntaxFactory.AreEquivalent(formatted, verified, false)) then file
                    else { file with Text = text }
        { generation with Files = generation.Files |> Array.map format }

    let private addPropertyText (existing: PocoExistingClass) (property: PocoExistingProperty) =
        let text = existing.Text
        let newline = lineEnding text |> Option.defaultValue "\n"
        let brace = existing.Declaration.CloseBraceToken.SpanStart
        let braceLine = lineStart text brace
        let preceding = text.Substring(braceLine, brace - braceLine)
        let atLineStart = String.IsNullOrWhiteSpace(preceding)
        let position = if atLineStart then braceLine else brace
        let declarationStart = existing.Declaration.SpanStart
        let start = lineStart text declarationStart
        let indent = text.Substring(start, declarationStart - start) |> Seq.takeWhile Char.IsWhiteSpace |> Seq.toArray |> String
        let memberIndent = indent + (indentation existing |> Option.defaultValue "    ")
        let body =
            property.Declaration.ToString().Replace("\r\n", "\n").Split('\n')
            |> Array.map (fun line -> memberIndent + line.Trim())
            |> String.concat newline
        position, (if atLineStart then "" else newline) + body + newline + (if atLineStart then "" else indent)

    let Compare (scan: PocoExistingScan, generated: PocoGeneratedFile array, allowManualEdits: bool) : PocoExistingComparison =
        let edits = ResizeArray<PocoExistingEdit>()
        let notices = ResizeArray<string>()
        let usage = Dictionary<string, int>(StringComparer.Ordinal)
        if allowManualEdits then
            for file in scan.Classes |> Array.distinctBy _.Path do
                for token in file.Declaration.SyntaxTree.GetRoot().DescendantTokens() do
                    if token.IsKind(SyntaxKind.IdentifierToken) then
                        match usage.TryGetValue(token.ValueText) with
                        | true, count -> usage.[token.ValueText] <- count + 1
                        | _ -> usage.Add(token.ValueText, 1)
        let byFullName = scan.Classes |> Array.groupBy _.FullName |> Map.ofArray
        let candidates (desired: PocoExistingClass) =
            match Map.tryFind desired.FullName byFullName with
            | Some matches -> matches
            | None when desired.TableName.IsSome ->
                let mapped =
                    scan.Classes |> Array.filter (fun item ->
                        item.TableName = desired.TableName &&
                        (item.Schema.IsNone || desired.Schema.IsNone || item.Schema = desired.Schema))
                if mapped.Length > 0 then mapped
                else
                    scan.Classes |> Array.filter (fun item ->
                        item.TableName.IsNone && item.Name = desired.Name &&
                        (desired.TableName = Some item.Name || item.SetName = desired.TableName))
            | _ -> [||]
        let appendEdit (existing: PocoExistingClass) description start length replacement requiresReview =
            edits.Add(
                { Id = existing.RelativePath + "|" + string start + "|" + description
                  RelativePath = existing.RelativePath; SourceHash = existing.SourceHash; Description = description
                  Start = start; Length = length; Replacement = replacement; RequiresReview = requiresReview })
        let difference existing description =
            if allowManualEdits then notices.Add(existing + " · " + description)
            else notices.Add(existing + " · " + description + " (manual source protected)")
        let inspectChanges (existing: PocoExistingClass) (desired: PocoExistingClass) =
            let mayEdit = allowManualEdits && existing.CanEdit
            let mayAddGenerated = not allowManualEdits && existing.GeneratedSource && existing.CanEdit
            let desiredColumns = desired.Properties |> Array.choose (fun property ->
                property.ColumnName |> Option.map (fun column -> column, property))
            for column, property in desiredColumns do
                let matched =
                    existing.Properties |> Array.filter (fun old ->
                        defaultArg old.ColumnName old.Name = column)
                match matched with
                | [| old |] when canonicalType old.Declaration.Type <> canonicalType property.Declaration.Type ->
                    let description = old.Name + " · type " + old.TypeName + " → " + property.TypeName
                    if mayEdit && autoProperty old then
                        let span = old.Declaration.Type.Span
                        appendEdit existing description span.Start span.Length property.TypeName true
                    else difference existing.FullName description
                | [| old |] ->
                    let oldLength = attributes "MaxLength" old.Declaration.AttributeLists |> Seq.map string |> Seq.toArray
                    let newLength = attributes "MaxLength" property.Declaration.AttributeLists |> Seq.map string |> Seq.toArray
                    if oldLength <> newLength then
                        notices.Add(existing.FullName + " · review length mapping for " + old.Name)
                | [||] ->
                    let description = "Add " + property.Name + " (" + column + ")"
                    let conflicts =
                        existing.Declaration.Members
                        |> Seq.exists (fun memberNode ->
                            memberNode.DescendantTokens() |> Seq.exists (fun token ->
                                token.IsKind(SyntaxKind.IdentifierToken) && token.ValueText = property.Name))
                    if (mayEdit || mayAddGenerated) && autoProperty property && not conflicts then
                        let position, text = addPropertyText existing property
                        appendEdit existing description position 0 text mayAddGenerated
                        if mayAddGenerated then
                            notices.Add(existing.RelativePath + " · Regenerating this source with its original generator can overwrite direct edits.")
                    else difference existing.FullName description
                | _ -> notices.Add(existing.FullName + " · ambiguous existing properties for " + column)
            let columns = desiredColumns |> Array.map fst |> Set.ofArray
            if not columns.IsEmpty then
                for property in existing.Properties do
                    match property.ColumnName with
                    | Some column when not (Set.contains column columns) ->
                        let description = "Remove " + property.Name + " · mapped column absent from proposed model"
                        let hasUsage = match usage.TryGetValue(property.Name) with true, count -> count > 1 | _ -> false
                        let otherAttributes =
                            property.Declaration.AttributeLists |> Seq.collect _.Attributes
                            |> Seq.exists (fun attribute ->
                                let name = simpleName (attribute.Name.ToString())
                                name <> "Column" && name <> "ColumnAttribute")
                        if mayEdit && autoProperty property && not hasUsage && not otherAttributes then
                            let span = property.Declaration.Span
                            appendEdit existing description span.Start span.Length "" true
                        else
                            let detail = if hasUsage then " · references found in inspected C# sources" else ""
                            difference existing.FullName (description + detail)
                    | _ -> ()
            for property in desired.Properties do
                if property.ColumnName.IsNone
                   && not (existing.Properties |> Array.exists (fun item ->
                       item.Name = property.Name && canonicalType item.Declaration.Type = canonicalType property.Declaration.Type)) then
                    notices.Add(existing.FullName + " · review relationship member " + property.Name + ".")
        for file in generated do
            if file.FileName.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) then
                let _, classes, bad = inspectText file.FileName file.FileName file.Text "" false CancellationToken.None
                if bad then notices.Add(file.FileName + " has invalid generated C# and cannot be merged.")
                else
                    for desired in classes do
                        match candidates desired with
                        | [| existing |] when desired.TableName.IsSome && desired.Properties |> Array.exists (fun p -> p.ColumnName.IsSome) ->
                            if (existing.TableName.IsSome && existing.TableName <> desired.TableName)
                               || (existing.Schema.IsSome && desired.Schema.IsSome && existing.Schema <> desired.Schema) then
                                notices.Add(existing.FullName + " maps to a different database object. Existing class was protected.")
                            else inspectChanges existing desired
                        | [| existing |] -> notices.Add(existing.FullName + " · existing non-entity code needs separate review.")
                        | [||] -> notices.Add(desired.FullName + " · no existing class match.")
                        | _ -> notices.Add(desired.FullName + " · several existing declarations match. Review the mapping before applying edits.")
        { Edits = edits.ToArray(); Notices = notices.ToArray() |> Array.distinct }

    let ApplyEdits (text: string, edits: PocoExistingEdit array) =
        let changes = edits |> Array.groupBy _.Start |> Array.sortByDescending fst
        let result = StringBuilder(text)
        let mutable boundary = text.Length
        for start, atPosition in changes do
            if start < 0 || start > boundary || (atPosition.Length > 1 && atPosition |> Array.exists (fun edit -> edit.Length <> 0)) then
                invalidArg (nameof edits) "The selected edits overlap or fall outside the source file."
            let length = atPosition.[0].Length
            if length < 0 || length > boundary - start then
                invalidArg (nameof edits) "The selected edit falls outside the source file."
            result.Remove(start, length).Insert(start, String.Concat(atPosition |> Array.map _.Replacement)) |> ignore
            boundary <- start
        let updated = result.ToString()
        if CSharpSyntaxTree.ParseText(updated).GetDiagnostics() |> Seq.exists (fun item -> item.Severity = DiagnosticSeverity.Error) then
            invalidArg (nameof edits) "The selected edits do not produce valid C# syntax."
        updated

    let private lambdaMembers (call: InvocationExpressionSyntax) =
        if call.ArgumentList.Arguments.Count = 0 then [||]
        else
            call.ArgumentList.Arguments.[0].Expression.DescendantNodesAndSelf().OfType<MemberAccessExpressionSyntax>()
            |> Seq.filter (fun access -> access.Expression :? IdentifierNameSyntax)
            |> Seq.map _.Name.Identifier.ValueText |> Seq.distinct |> Seq.sort |> Seq.toArray
    let private inChain names (call: InvocationExpressionSyntax) =
        call.DescendantNodesAndSelf().OfType<InvocationExpressionSyntax>()
        |> Seq.tryFind (fun invocation -> List.contains (methodName invocation) names)
    let private ownerOfRelationship (call: InvocationExpressionSyntax) =
        let genericChild = genericArgument "HasForeignKey" call.Expression
        let direct = genericArgument "Entity" call
        let configuration =
            call.Ancestors().OfType<MethodDeclarationSyntax>()
            |> Seq.tryPick (fun methodNode ->
                methodNode.ParameterList.Parameters |> Seq.tryPick (fun parameter ->
                    if isNull parameter.Type then None else genericArgument "EntityTypeBuilder" parameter.Type))
            |> Option.orElseWith (fun () ->
                call.Ancestors().OfType<ClassDeclarationSyntax>() |> Seq.tryPick (fun declaration ->
                    if isNull declaration.BaseList then None else genericArgument "EntityTypeConfiguration" declaration.BaseList))
        genericChild |> Option.orElse direct |> Option.orElse configuration |> Option.map simpleName
    let private fkKey (names: string array) = String.Join(",", names |> Array.sort)
    let private relationshipNames (roots: seq<SyntaxNode>) =
        let roots = roots |> Seq.toArray
        let classes = roots |> Array.collect (fun root -> root.DescendantNodes().OfType<ClassDeclarationSyntax>() |> Seq.toArray)
        let collectionType owner property =
            classes |> Seq.filter (fun declaration -> declaration.Identifier.ValueText = owner)
            |> Seq.collect (fun declaration -> declaration.Members.OfType<PropertyDeclarationSyntax>())
            |> Seq.filter (fun declaration -> declaration.Identifier.ValueText = property)
            |> Seq.tryPick (fun declaration ->
                [ "ICollection"; "IEnumerable"; "IList"; "List"; "HashSet"; "ISet" ]
                |> List.tryPick (fun name -> genericArgument name declaration.Type)
                |> Option.map simpleName)
        roots |> Seq.collect (fun root -> root.DescendantNodes().OfType<InvocationExpressionSyntax>())
        |> Seq.filter (fun call -> methodName call = "HasForeignKey")
        |> Seq.choose (fun call ->
            match ownerOfRelationship call, inChain [ "HasOne"; "HasRequired"; "HasOptional" ] call with
            | Some child, Some parent when (lambdaMembers call).Length > 0 && (lambdaMembers parent).Length = 1 ->
                let inverse = inChain [ "WithMany"; "WithOne"; "WithOptional"; "WithRequired" ] call
                              |> Option.bind (fun inverse -> lambdaMembers inverse |> Array.tryHead)
                Some((child, fkKey (lambdaMembers call)), (lambdaMembers parent).[0], inverse)
            | _ ->
                // EF6 reverse-POCO commonly declares the same FK from the
                // principal side: HasMany(...).WithRequired/Optional(...).
                match ownerOfRelationship call, inChain [ "HasMany" ] call,
                      inChain [ "WithRequired"; "WithOptional"; "WithOne" ] call with
                | Some parent, Some children, Some toParent when (lambdaMembers call).Length > 0
                                                                && (lambdaMembers children).Length = 1
                                                                && (lambdaMembers toParent).Length = 1 ->
                    let inverse = (lambdaMembers children).[0]
                    collectionType parent inverse |> Option.map (fun child ->
                        (child, fkKey (lambdaMembers call)), (lambdaMembers toParent).[0], Some inverse)
                | _ -> None)
        |> Seq.groupBy (fun (relationship, _, _) -> relationship)
        |> Seq.choose (fun (relationship, items) ->
            items |> Seq.map (fun (_, parent, inverse) -> parent, inverse) |> one |> Option.map (fun value -> relationship, value))
        |> Map.ofSeq

    let private selectContext (scan: PocoExistingScan) (options: PocoOptions) =
        let contexts = contextCandidates scan.Classes
        let selected = contexts |> Array.filter (fun context -> context.Name = options.ContextName && context.Namespace = options.Namespace)
        match selected, contexts with
        | [| context |], _ -> context
        | _, [| context |] -> context
        | _ -> invalidArg (nameof scan) "Choose one concrete DbContext in Advanced."

    let private requireCompleteContext (context: PocoExistingClass) (token: CancellationToken) =
        let partialExport =
            context.Declaration.SyntaxTree.GetRoot(token).DescendantTrivia()
            |> Seq.exists (fun trivia ->
                trivia.IsKind(SyntaxKind.SingleLineCommentTrivia)
                && trivia.ToString().Contains("therefore only a few tables/views/stored procedures are generated.", StringComparison.OrdinalIgnoreCase))
        if partialExport then
            invalidOp ("The selected T4 source " + context.RelativePath
                       + " reports a partial export. Choose the last complete working C# model from Git or a saved copy before generating a replacement.")

    /// Rebuild from the working model's public contract, not from naming guesses.
    /// Original method bodies remain executable (including List, async and DataSet
    /// procedures); schema changes are applied to their existing entity classes.
    let private generateCompatible allowNullableSyntax
        (scan: PocoExistingScan, snapshot: PocoSchemaSnapshot, options: PocoOptions, token: CancellationToken) : PocoGeneration =
        if options.Target <> PocoTarget.Ef6 || scan.Target = Some PocoTarget.EfCore then
            invalidArg "scan" "This standalone generator supports EF6 source models only."
        let context = selectContext scan options
        requireCompleteContext context token
        let namespaceName = context.Namespace
        let inferred = Overrides(scan, snapshot.Objects |> Array.map _.Item)
        let mergedOverrides =
            options.Overrides |> Map.fold (fun state objectKey names -> Map.add objectKey names state) inferred
        let options =
            { options with Namespace = namespaceName; ContextName = context.Name
                           Target = defaultArg scan.Target options.Target
                           NullableReferenceTypes = allowNullableSyntax && defaultArg scan.NullableReferenceTypes options.NullableReferenceTypes
                           Overrides = mergedOverrides }
        let generation = PocoCodeGeneration.Generate snapshot options |> fun result -> FormatGenerated(scan, result, token)
        let warnings = ResizeArray<string>(generation.Warnings)
        let matches = Matches(scan, snapshot.Objects |> Array.map _.Item)
        let filesByPath = scan.Files |> Array.map (fun file -> file.RelativePath, file) |> Map.ofArray
        let roots =
            scan.Files |> Array.map (fun file ->
                token.ThrowIfCancellationRequested()
                file.RelativePath, CSharpSyntaxTree.ParseText(file.Text, cancellationToken = token).GetCompilationUnitRoot(token))
            |> Map.ofArray
        // Follow referenced source types, including interface-only files. This keeps
        // helpers/results, but does not copy unrelated controllers or app startup.
        let bySimpleName =
            roots |> Map.toSeq |> Seq.collect (fun (path, root) ->
                root.DescendantNodes() |> Seq.choose (function
                    | :? BaseTypeDeclarationSyntax as declaration -> Some(declaration.Identifier.ValueText, path)
                    | :? DelegateDeclarationSyntax as declaration -> Some(declaration.Identifier.ValueText, path)
                    | _ -> None))
            |> Seq.groupBy fst
            |> Seq.map (fun (name, values) -> name, values |> Seq.map snd |> Seq.distinct |> Seq.toArray)
            |> Map.ofSeq
        let included = HashSet<string>(StringComparer.OrdinalIgnoreCase)
        let pending = Queue<string>()
        let includeFile path = if filesByPath.ContainsKey path && included.Add path then pending.Enqueue path
        for item in scan.Classes do
            if item.FullName = context.FullName || item.TableName.IsSome || item.SetName.IsSome then includeFile item.RelativePath
        for KeyValue(path, root) in roots do
            let globalUsing = root.Usings |> Seq.exists (fun directive -> directive.GlobalKeyword.IsKind(SyntaxKind.GlobalKeyword))
            let extensions = root.DescendantNodes().OfType<MethodDeclarationSyntax>() |> Seq.exists (fun methodNode ->
                methodNode.ParameterList.Parameters.Count > 0 && methodNode.ParameterList.Parameters.[0].Modifiers.Any(SyntaxKind.ThisKeyword))
            if globalUsing || extensions then includeFile path
        while pending.Count > 0 do
            token.ThrowIfCancellationRequested()
            let path = pending.Dequeue()
            for symbol in roots.[path].DescendantTokens() do
                if symbol.IsKind(SyntaxKind.IdentifierToken) then
                    match Map.tryFind symbol.ValueText bySimpleName with
                    | Some dependencies -> for file in dependencies do includeFile file
                    | None -> ()
        let includedTypes =
            included |> Seq.collect (fun path -> TypeDeclarations roots.[path] |> Seq.map fst) |> Set.ofSeq
        let existingByFull = scan.Classes |> Array.groupBy _.FullName |> Map.ofArray
        let proposedRoots =
            generation.Files |> Array.map (fun file ->
                token.ThrowIfCancellationRequested()
                file, CSharpSyntaxTree.ParseText(file.Text, cancellationToken = token).GetCompilationUnitRoot(token))
        let routineExecutor (root: SyntaxNode) =
            root.DescendantNodes().OfType<ClassDeclarationSyntax>()
            |> Seq.tryFind (fun declaration ->
                declaration.Identifier.ValueText.EndsWith("Procedure", StringComparison.Ordinal)
                && declaration.Modifiers.Any(SyntaxKind.StaticKeyword))
            |> Option.map (fun declaration -> snd (sourceName declaration declaration.Identifier.ValueText))
        let routineApi (root: SyntaxNode) =
            let syntaxText (node: SyntaxNode) = node.WithoutTrivia().NormalizeWhitespace().ToString()
            root.DescendantNodes().OfType<ClassDeclarationSyntax>()
            |> Seq.filter (fun declaration -> snd (sourceName declaration declaration.Identifier.ValueText) <> context.FullName)
            |> Seq.collect (fun declaration ->
                let name = snd (sourceName declaration declaration.Identifier.ValueText)
                declaration.Members |> Seq.choose (function
                    | :? MethodDeclarationSyntax as methodNode when methodNode.Modifiers.Any(SyntaxKind.PublicKeyword) ->
                        Some (name, methodNode.Identifier.ValueText, syntaxText methodNode.ReturnType, syntaxText methodNode.ParameterList)
                    | :? PropertyDeclarationSyntax as property when property.Modifiers.Any(SyntaxKind.PublicKeyword) ->
                        Some (name, property.Identifier.ValueText, syntaxText property.Type, "")
                    | _ -> None))
            |> Set.ofSeq
        let oldRoutines =
            included
            |> Seq.choose (fun path ->
                if filesByPath.[path].Text.Contains("// <auto-generated by AnotherEdit>", StringComparison.Ordinal) then
                    routineExecutor roots.[path] |> Option.map (fun name -> name, roots.[path])
                else None)
            |> Map.ofSeq
        let generatedRoots =
            proposedRoots |> Array.filter (fun (_, root) ->
                match routineExecutor root with
                | Some name when
                    Map.tryFind name oldRoutines |> Option.exists (fun old -> not (Set.isSubset (routineApi old) (routineApi root))) ->
                    // The copied context still calls the old executor. Keep it with its DTOs
                    // and skip the fresh facade when database metadata would change that API.
                    warnings.Add(name + ": Existing procedure API retained. Current metadata would change its signatures or result types.")
                    false
                | _ -> true)
        let freshTypes = generatedRoots |> Seq.collect (fun (_, root) -> TypeDeclarations root |> Seq.map fst) |> Set.ofSeq
        let refreshedSources =
            included |> Seq.filter (fun path ->
                let text = filesByPath.[path].Text
                let types = TypeDeclarations roots.[path] |> Seq.map fst |> Seq.toArray
                text.Contains("// <auto-generated by AnotherEdit>", StringComparison.Ordinal)
                && types.Length > 0 && not (types |> Array.contains context.FullName)
                && (types |> Array.forall freshTypes.Contains))
            |> Set.ofSeq
        let preservedTypes =
            refreshedSources |> Seq.collect (fun path -> TypeDeclarations roots.[path] |> Seq.map fst)
            |> Seq.fold (fun types name -> Set.remove name types) includedTypes
        let generatedClasses =
            generatedRoots |> Array.collect (fun (file, root) ->
                let _, classes, _ = inspectText file.FileName file.FileName file.Text "" false token
                classes)
        let generatedByName = generatedClasses |> Array.groupBy _.Name |> Map.ofArray
        let edits = Dictionary<string, ResizeArray<PocoExistingEdit>>(StringComparer.OrdinalIgnoreCase)
        let addEdit path start length replacement description =
            let source = filesByPath.[path]
            let item = { Id = Guid.NewGuid().ToString("N"); RelativePath = path; SourceHash = source.SourceHash
                         Description = description; Start = start; Length = length; Replacement = replacement; RequiresReview = false }
            match edits.TryGetValue path with
            | true, items -> items.Add item
            | _ -> let items = ResizeArray<PocoExistingEdit>() in items.Add item; edits.Add(path, items)
        let defaultAnnotations path =
            let text = filesByPath.[path].Text
            let header = text.Substring(0, min text.Length 4096)
            // C# generated sources begin in an oblivious annotation context even
            // when their project enables NRT. Keep that old public contract.
            if header.IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0
               || header.IndexOf("<autogenerated", StringComparison.OrdinalIgnoreCase) >= 0 then false
            else defaultArg scan.NullableReferenceTypes false
        let annotationsAt path position =
            let mutable enabled = defaultAnnotations path
            for trivia in roots.[path].DescendantTrivia(descendIntoTrivia = true) do
                if trivia.SpanStart < position then
                    match trivia.GetStructure() with
                    | :? NullableDirectiveTriviaSyntax as directive when directive.TargetToken.ValueText <> "warnings" ->
                        match directive.SettingToken.ValueText with
                        | "enable" -> enabled <- true
                        | "disable" -> enabled <- false
                        | "restore" -> enabled <- defaultAnnotations path
                        | _ -> ()
                    | _ -> ()
            enabled
        let appendMember (owner: PocoExistingClass) (memberNode: MemberDeclarationSyntax) =
            let newline = lineEnding owner.Text |> Option.defaultValue Environment.NewLine
            let start = owner.Declaration.CloseBraceToken.SpanStart
            let position = lineStart owner.Text start
            let prefix = lineIndent owner.Text start |> Option.defaultValue ""
            let indent = prefix + (indentation owner |> Option.defaultValue "    ")
            let body = memberNode.NormalizeWhitespace(indentation = "    ", eol = newline).ToFullString()
            let formatted = body.Replace("\r\n", "\n").Split('\n') |> Array.map (fun line -> indent + line) |> String.concat newline
            let formatted =
                if not allowNullableSyntax || annotationsAt owner.RelativePath start then formatted
                else indent + "#nullable enable annotations" + newline + formatted + newline + indent + "#nullable disable annotations"
            if owner.Text.Substring(position, start - position) |> Seq.forall Char.IsWhiteSpace then
                addEdit owner.RelativePath position 0 (formatted + newline) "Refresh model member"
            else addEdit owner.RelativePath start 0 (newline + formatted + newline + prefix) "Refresh model member"
        let scalar (property: PocoExistingProperty) =
            attributes "Column" property.Declaration.AttributeLists |> Seq.isEmpty |> not
        let sameReferenceType (left: TypeSyntax) (right: TypeSyntax) =
            let leftName = (canonicalType left).TrimEnd('?')
            let rightName = (canonicalType right).TrimEnd('?')
            leftName = rightName && (leftName = "string" || leftName = "object" || leftName.EndsWith("]", StringComparison.Ordinal))
        let syncProperties (existing: PocoExistingClass) (desired: PocoExistingClass) includeNavigation =
            let parts = existingByFull.[existing.FullName]
            let current = parts |> Array.collect _.Properties |> Array.map (fun property -> property.Name, property) |> Map.ofArray
            for property in desired.Properties do
                if includeNavigation || scalar property then
                    match Map.tryFind property.Name current with
                    | Some previous when canonicalType previous.Declaration.Type <> canonicalType property.Declaration.Type
                                         && not (sameReferenceType previous.Declaration.Type property.Declaration.Type) && scalar property ->
                        // Retain accessors, attributes, initializer and constructor defaults.
                        let owner = parts |> Array.find (fun part -> part.Properties |> Array.exists (fun p -> obj.ReferenceEquals(p.Declaration, previous.Declaration)))
                        addEdit owner.RelativePath previous.Declaration.Type.SpanStart previous.Declaration.Type.Span.Length
                            (property.Declaration.Type.ToString()) ("Update type " + existing.Name + "." + property.Name)
                    | Some _ -> ()
                    | None -> appendMember existing (property.Declaration :> MemberDeclarationSyntax)
        // Navigation names are public API as well. Reuse the old name when a
        // relationship's target and cardinality identify one existing navigation.
        let navigationTarget (syntax: TypeSyntax) =
            let text = syntax.ToString().TrimEnd('?')
            let collection = Regex.Match(text, @"(?:ICollection|IEnumerable|IList|List|HashSet|ISet)<(.+)>")
            if collection.Success then true, simpleName (collection.Groups.[1].Value.TrimEnd('?'))
            else false, simpleName text
        let navigationNames = Dictionary<string * string, string>()
        let oldRelationships = relationshipNames(included |> Seq.map (fun path -> roots.[path] :> SyntaxNode))
        // Matching a FK's member list disambiguates two navigations to the same
        // table, a common pattern where target-type-only matching is insufficient.
        for generated in generatedClasses |> Array.filter (fun item -> item.Name = options.ContextName) do
            for call in generated.Declaration.DescendantNodes().OfType<InvocationExpressionSyntax>() do
                if methodName call = "HasForeignKey" then
                    match ownerOfRelationship call, inChain [ "HasOne"; "HasRequired"; "HasOptional" ] call with
                    | Some child, Some parent ->
                        let names = lambdaMembers parent
                        match Map.tryFind (child, fkKey (lambdaMembers call)) oldRelationships with
                        | Some(oldParent, oldInverse) when names.Length = 1 ->
                            navigationNames.[(child, names.[0])] <- oldParent
                            let inverse = inChain [ "WithMany"; "WithOne"; "WithOptional"; "WithRequired" ] call
                                          |> Option.bind (fun inverse -> lambdaMembers inverse |> Array.tryHead)
                            let parentType = generatedClasses |> Array.tryFind (fun item -> item.Name = child)
                                             |> Option.bind (fun item -> item.Properties |> Array.tryFind (fun property -> property.Name = names.[0]))
                                             |> Option.map (fun property -> navigationTarget property.Declaration.Type |> snd)
                            match parentType, inverse, oldInverse with
                            | Some parentType, Some inverse, Some oldInverse -> navigationNames.[(parentType, inverse)] <- oldInverse
                            | _ -> ()
                        | _ -> ()
                    | _ -> ()
        let tablePairs = ResizeArray<PocoObject * PocoExistingClass * PocoExistingClass>()
        for source in snapshot.Objects do
            match Map.tryFind (key source.Item) matches with
            | Some existing ->
                match Map.tryFind (PocoCodeGeneration.Names options source.Item).ClassName generatedByName with
                | Some [| desired |] ->
                    tablePairs.Add(source, existing, desired)
                    let existingProperties = existingByFull.[existing.FullName] |> Array.collect _.Properties
                    for property in desired.Properties |> Array.filter (scalar >> not) do
                        let preferred =
                            match navigationNames.TryGetValue((desired.Name, property.Name)) with
                            | true, name -> existingProperties |> Array.tryFind (fun old -> old.Name = name)
                            | _ -> None
                        let exact = existingProperties |> Array.tryFind (fun old ->
                            old.Name = property.Name && navigationTarget old.Declaration.Type = navigationTarget property.Declaration.Type)
                        let candidates =
                            existingProperties |> Array.filter (fun old ->
                                navigationTarget old.Declaration.Type = navigationTarget property.Declaration.Type)
                        let previous = preferred |> Option.orElse exact |> Option.orElse (if candidates.Length = 1 then Some candidates.[0] else None)
                        match previous with
                        | Some old -> navigationNames.[(desired.Name, property.Name)] <- old.Name
                        | None -> ()
                    // Refresh scalars first; navigation insertion uses the chosen old names.
                    syncProperties existing desired false
                    for property in desired.Properties |> Array.filter (scalar >> not) do
                        if not (navigationNames.ContainsKey(desired.Name, property.Name)) then
                            appendMember existing (property.Declaration :> MemberDeclarationSyntax)
                | _ -> ()
            | None -> ()
        let renameNavigation className name =
            match navigationNames.TryGetValue((className, name)) with true, value -> value | _ -> name
        let replaceNavigation (statement: StatementSyntax) =
            let text = statement.ToString()
            let entity = Regex.Match(text, @"modelBuilder\.Entity<(?<type>[^>]+)>\(\)")
            if not entity.Success || not (text.Contains(".HasOne(") || text.Contains(".HasRequired(") || text.Contains(".HasOptional(")) then statement
            else
                let className = simpleName entity.Groups.["type"].Value
                let parent = Regex.Match(text, @"\.(?:HasOne|HasRequired|HasOptional)\(e => e\.(?<property>\w+)\)")
                if not parent.Success then statement
                else
                    let propertyName = parent.Groups.["property"].Value
                    let parentType =
                        generatedClasses |> Array.tryFind (fun item -> item.Name = className)
                        |> Option.bind (fun item -> item.Properties |> Array.tryFind (fun property -> property.Name = propertyName))
                        |> Option.map (fun property -> navigationTarget property.Declaration.Type |> snd)
                    let text = text.Replace("e => e." + propertyName + ")", "e => e." + renameNavigation className propertyName + ")")
                    let text =
                        match parentType with
                        | Some parentName -> Regex.Replace(text, @"(\.(?:WithMany|WithOne|WithOptional)\(e => e\.)(\w+)(\))",
                                                MatchEvaluator(fun found -> found.Groups.[1].Value + renameNavigation parentName found.Groups.[2].Value + found.Groups.[3].Value))
                        | None -> text
                    SyntaxFactory.ParseStatement(text)
        let removedScalarProperties =
            [| for _, existing, desired in tablePairs do
                   let live = desired.Properties |> Array.filter scalar |> Array.map _.Name |> Set.ofArray
                   for property in existingByFull.[existing.FullName] |> Array.collect _.Properties do
                       let isKnownScalar = property.ColumnName.IsSome || Regex.IsMatch(canonicalType property.Declaration.Type, @"^(?:string|bool|byte|short|int|long|float|double|decimal|char|Guid|DateTime|DateTimeOffset|TimeSpan|System\.(?:Guid|DateTime|DateTimeOffset|TimeSpan))(?:\?|\[\])?$")
                       if isKnownScalar && not (live.Contains property.Name) then
                           warnings.Add(existing.FullName + "." + property.Name + " no longer has a database column; its public property is retained and ignored by EF.")
                           yield existing, property |]
        let generatedContextParts = generatedClasses |> Array.filter (fun item -> item.FullName = context.FullName)
        let generatedContext =
            generatedContextParts |> Array.tryFind (fun item ->
                item.Declaration.Members.OfType<MethodDeclarationSyntax>() |> Seq.exists (fun methodNode -> methodNode.Identifier.ValueText = "OnModelCreating"))
            |> Option.orElse (generatedContextParts |> Array.tryHead)
        match generatedContext with
        | Some desiredContext ->
            let contextParts = existingByFull.[context.FullName]
            let members = contextParts |> Array.collect (fun item -> item.Declaration.Members |> Seq.toArray)
            let existingImports = roots.[context.RelativePath].DescendantNodes().OfType<UsingDirectiveSyntax>() |> Seq.map _.ToString() |> Set.ofSeq
            let requiredImports =
                generatedRoots |> Seq.filter (fun (_, root) ->
                    root.DescendantNodes().OfType<ClassDeclarationSyntax>() |> Seq.exists (fun declaration ->
                        snd (sourceName declaration declaration.Identifier.ValueText) = context.FullName))
                |> Seq.collect (fun (_, root) -> root.DescendantNodes().OfType<UsingDirectiveSyntax>())
                |> Seq.map _.ToString() |> Seq.filter (existingImports.Contains >> not) |> Seq.distinct |> Seq.toArray
            if requiredImports.Length > 0 then
                let originalRoot = roots.[context.RelativePath]
                let position =
                    if originalRoot.Usings.Count > 0 then originalRoot.Usings.[0].SpanStart
                    elif originalRoot.Members.Count > 0 then originalRoot.Members.[0].SpanStart
                    else 0
                let newline = lineEnding context.Text |> Option.defaultValue Environment.NewLine
                addEdit context.RelativePath position 0 (String.Join(newline, requiredImports) + newline) "Required procedure extension namespaces"
            let propertyNames = HashSet<string>(members.OfType<PropertyDeclarationSyntax>() |> Seq.map _.Identifier.ValueText, StringComparer.Ordinal)
            let rec signatureType (syntax: TypeSyntax) =
                match syntax with
                | :? NullableTypeSyntax as nullable ->
                    let inner = signatureType nullable.ElementType
                    if [ "bool"; "byte"; "sbyte"; "short"; "ushort"; "int"; "uint"; "long"; "ulong"; "float"; "double"; "decimal"; "char"; "Guid"; "DateTime"; "DateTimeOffset"; "TimeSpan" ] |> List.contains inner then inner + "?" else inner
                | :? ArrayTypeSyntax as array -> signatureType array.ElementType + String.Concat(array.RankSpecifiers |> Seq.map string)
                | :? QualifiedNameSyntax as qualified -> signatureType qualified.Right
                | :? AliasQualifiedNameSyntax as alias -> signatureType alias.Name
                | :? GenericNameSyntax as generic ->
                    generic.Identifier.ValueText + "<" + String.Join(",", generic.TypeArgumentList.Arguments |> Seq.map signatureType) + ">"
                | _ ->
                    let text = syntax.ToString()
                    clrNames |> Map.toSeq |> Seq.tryPick (fun (name, alias) -> if simpleName name = text then Some alias else None) |> Option.defaultValue text
            let methodSignature (methodNode: MethodDeclarationSyntax) =
                methodNode.Identifier.ValueText,
                (if isNull methodNode.TypeParameterList then 0 else methodNode.TypeParameterList.Parameters.Count),
                methodNode.ParameterList.Parameters |> Seq.map (fun parameter ->
                    (if parameter.Modifiers.Any(SyntaxKind.OutKeyword) || parameter.Modifiers.Any(SyntaxKind.RefKeyword) || parameter.Modifiers.Any(SyntaxKind.InKeyword) then "ref:" else "") + signatureType parameter.Type) |> Seq.toList
            let methodNames = HashSet<_>(members.OfType<MethodDeclarationSyntax>() |> Seq.map methodSignature)
            let originalMethodNames = members.OfType<MethodDeclarationSyntax>() |> Seq.map _.Identifier.ValueText |> Set.ofSeq
            for part in generatedContextParts do
                for memberNode in part.Declaration.Members do
                    match memberNode with
                    | :? PropertyDeclarationSyntax as property when propertyNames.Add property.Identifier.ValueText -> appendMember context memberNode
                    | :? MethodDeclarationSyntax as methodNode when methodNode.Modifiers.Any(SyntaxKind.PublicKeyword)
                                                                   && not (methodNames.Contains(methodSignature methodNode)) ->
                        let structuredOutput = methodNode.ParameterList.Parameters |> Seq.exists (fun parameter -> parameter.Modifiers.Any(SyntaxKind.OutKeyword))
                        let methodNode =
                            if structuredOutput && originalMethodNames.Contains methodNode.Identifier.ValueText then
                                // Do not make old Foo(value, out var status) calls ambiguous
                                // with a newly introduced structured Outputs overload.
                                methodNode.WithIdentifier(SyntaxFactory.Identifier(methodNode.Identifier.ValueText + "WithOutputs"))
                            else methodNode
                        if methodNames.Add(methodSignature methodNode) then appendMember context (methodNode :> MemberDeclarationSyntax)
                    | _ -> ()
            let freshMapping =
                desiredContext.Declaration.Members.OfType<MethodDeclarationSyntax>()
                |> Seq.tryFind (fun item -> item.Identifier.ValueText = "OnModelCreating")
            let oldMapping =
                contextParts |> Array.collect (fun item -> item.Declaration.Members.OfType<MethodDeclarationSyntax>() |> Seq.toArray)
                |> Array.tryFind (fun item -> item.Identifier.ValueText = "OnModelCreating")
            match freshMapping, oldMapping with
            | Some fresh, Some old when not (isNull old.Body) ->
                let newline = lineEnding context.Text |> Option.defaultValue Environment.NewLine
                let mappingSource = contextParts |> Array.find (fun item -> item.Declaration.Span.Contains(old.Span))
                let indent = lineIndent mappingSource.Text old.SpanStart |> Option.defaultValue "        "
                let statements =
                    fresh.Body.Statements |> Seq.filter (fun statement ->
                        let text = statement.ToString()
                        not (text.StartsWith("base.OnModelCreating", StringComparison.Ordinal)
                             || text.StartsWith("OnModelCreatingPartial", StringComparison.Ordinal)))
                    |> Seq.map replaceNavigation |> Seq.toArray
                let builderName = if old.ParameterList.Parameters.Count > 0 then old.ParameterList.Parameters.[0].Identifier.ValueText else "modelBuilder"
                let beginMarker = "// <AnotherEdit.CurrentSchema>"
                let endMarker = "// </AnotherEdit.CurrentSchema>"
                let body = StringBuilder(indent + "    " + beginMarker + newline + indent + "    // Current database schema; existing public methods and defaults are retained." + newline)
                for statement in statements do
                    let text = statement.NormalizeWhitespace(indentation = "    ", eol = newline).ToFullString().Replace("modelBuilder", builderName)
                    for line in text.Replace("\r\n", "\n").Split('\n') do body.Append(indent).Append("    ").AppendLine(line) |> ignore
                for existing, property in removedScalarProperties do
                    body.Append(indent).Append("    ").Append(builderName).Append(".Entity<").Append(existing.Name).Append(">().Ignore(e => e.").Append(property.Name).AppendLine(");") |> ignore
                body.Append(indent).Append("    ").Append(endMarker).Append(newline) |> ignore
                let startMarker = mappingSource.Text.IndexOf(beginMarker, old.Body.SpanStart, old.Body.Span.Length, StringComparison.Ordinal)
                let finishMarker = mappingSource.Text.IndexOf(endMarker, old.Body.SpanStart, old.Body.Span.Length, StringComparison.Ordinal)
                if startMarker >= 0 && finishMarker > startMarker then
                    let start = lineStart mappingSource.Text startMarker
                    let finishLine = mappingSource.Text.IndexOf('\n', finishMarker)
                    let finish = if finishLine < 0 then finishMarker + endMarker.Length else finishLine + 1
                    addEdit mappingSource.RelativePath start (finish - start) (body.ToString()) "Replace current EF mappings"
                else
                    let close = old.Body.CloseBraceToken.SpanStart
                    let start = lineStart mappingSource.Text close
                    if mappingSource.Text.Substring(start, close - start) |> Seq.forall Char.IsWhiteSpace then
                        addEdit mappingSource.RelativePath start 0 (body.ToString()) "Refresh current EF mappings"
                    else addEdit mappingSource.RelativePath close 0 (newline + body.ToString() + indent) "Refresh current EF mappings"
            | Some fresh, None ->
                let statements =
                    fresh.Body.Statements
                    |> Seq.filter (fun statement ->
                        let text = statement.ToString()
                        not (text.StartsWith("OnModelCreatingPartial", StringComparison.Ordinal) || text.StartsWith("base.OnModelCreating", StringComparison.Ordinal)))
                    |> Seq.map replaceNavigation
                let body =
                    "{\nbase.OnModelCreating(modelBuilder);\n// <AnotherEdit.CurrentSchema>\n"
                    + "// Current database schema; existing public methods and defaults are retained.\n"
                    + String.Join("\n", statements |> Seq.map string)
                    + String.Concat(removedScalarProperties |> Seq.map (fun (existing, property) -> "\nmodelBuilder.Entity<" + existing.Name + ">().Ignore(e => e." + property.Name + ");"))
                    + "\n// </AnotherEdit.CurrentSchema>\n}"
                appendMember context (fresh.WithBody(SyntaxFactory.ParseStatement(body) :?> BlockSyntax) :> MemberDeclarationSyntax)
            | Some _, Some _ -> warnings.Add(context.FullName + ": expression-bodied OnModelCreating was preserved; add a block body to merge current schema mappings.")
            | _ -> ()
        | None -> ()
        // Associate a stored procedure's actual command text with its existing
        // result DTO. A List<T> remains a List<T>, never a single-row projection.
        for source in snapshot.Objects |> Array.filter (fun item -> item.Item.Kind = SqlCatalogObjectKind.Procedure) do
            let desiredName = (PocoCodeGeneration.Names options source.Item).ClassName + "Row"
            match Map.tryFind desiredName generatedByName with
            | Some [| desired |] ->
                let resultTypes = HashSet<string>(StringComparer.Ordinal)
                for methodNode in existingByFull.[context.FullName] |> Seq.collect (fun part -> part.Declaration.Members.OfType<MethodDeclarationSyntax>()) do
                    let callsProcedure =
                        methodNode.DescendantNodes().OfType<LiteralExpressionSyntax>()
                        |> Seq.exists (fun literal ->
                            literal.IsKind(SyntaxKind.StringLiteralExpression)
                            && Regex.IsMatch(literal.Token.ValueText.Replace("[", "").Replace("]", ""),
                                             @"(?<![\p{L}\p{Nd}_])" + Regex.Escape(source.Item.Name) + @"(?![\p{L}\p{Nd}_])", RegexOptions.IgnoreCase))
                    if callsProcedure then
                        for generic in methodNode.DescendantNodes().OfType<GenericNameSyntax>() do
                            if [ "Set"; "SqlQuery"; "ExecuteStoreQuery" ] |> List.contains generic.Identifier.ValueText then
                                for argument in generic.TypeArgumentList.Arguments do resultTypes.Add(simpleName(argument.ToString())) |> ignore
                for name in resultTypes do
                    let candidates = scan.Classes |> Array.filter (fun item -> item.Name = name)
                    if candidates.Length = 1 then
                        // Routine rows do not carry ColumnAttribute in the baseline.
                        let properties = desired.Properties |> Array.map (fun property ->
                            let annotation = SyntaxFactory.AttributeList(SyntaxFactory.SingletonSeparatedList(
                                                SyntaxFactory.Attribute(SyntaxFactory.ParseName("global::System.ComponentModel.DataAnnotations.Schema.ColumnAttribute"))
                                                    .WithArgumentList(SyntaxFactory.AttributeArgumentList(SyntaxFactory.SingletonSeparatedList(
                                                        SyntaxFactory.AttributeArgument(SyntaxFactory.LiteralExpression(SyntaxKind.StringLiteralExpression, SyntaxFactory.Literal(property.Name))))))))
                            { property with Declaration = property.Declaration.AddAttributeLists annotation })
                        syncProperties candidates.[0] { desired with Properties = properties } false
            | _ -> ()
        let output = ResizeArray<PocoGeneratedFile>()
        let canonicalMappingRegions (text: string) =
            // Creating a whole method and refreshing only its owned region must
            // produce exactly the same layout on the following generation.
            let root = CSharpSyntaxTree.ParseText(text, cancellationToken = token).GetCompilationUnitRoot(token)
            let replacements = ResizeArray<int * int * string>()
            for methodNode in root.DescendantNodes().OfType<MethodDeclarationSyntax>() do
                if methodNode.Identifier.ValueText = "OnModelCreating" && not (isNull methodNode.Body) then
                    let beginMarker = "// <AnotherEdit.CurrentSchema>"
                    let endMarker = "// </AnotherEdit.CurrentSchema>"
                    let start = text.IndexOf(beginMarker, methodNode.Body.SpanStart, methodNode.Body.Span.Length, StringComparison.Ordinal)
                    let finish = text.IndexOf(endMarker, methodNode.Body.SpanStart, methodNode.Body.Span.Length, StringComparison.Ordinal)
                    if start >= 0 && finish > start then
                        let region = text.Substring(start + beginMarker.Length, finish - start - beginMarker.Length)
                        let block = SyntaxFactory.ParseStatement("{" + region + "}") :?> BlockSyntax
                        let newline = lineEnding text |> Option.defaultValue Environment.NewLine
                        let indent = (lineIndent text methodNode.SpanStart |> Option.defaultValue "") + (indentation context |> Option.defaultValue "    ")
                        let body = StringBuilder(indent + beginMarker + newline + indent + "// Current database schema; existing public methods and defaults are retained." + newline)
                        for statement in block.Statements do
                            let rendered = statement.WithoutLeadingTrivia().WithoutTrailingTrivia().NormalizeWhitespace(indentation = "    ", eol = newline).ToFullString()
                            for line in rendered.Replace("\r\n", "\n").Split('\n') do
                                body.Append(indent).Append(line).Append(newline) |> ignore
                        body.Append(indent).Append(endMarker).Append(newline) |> ignore
                        let endLine = text.IndexOf('\n', finish)
                        let after = if endLine < 0 then finish + endMarker.Length else endLine + 1
                        let before = lineStart text start
                        replacements.Add(before, after - before, body.ToString())
            let result = StringBuilder(text)
            for start, length, replacement in replacements |> Seq.sortByDescending (fun (start, _, _) -> start) do
                result.Remove(start, length).Insert(start, replacement) |> ignore
            result.ToString()
        let outputName (source: PocoExistingSource) =
            // After migration the scan root may be the consuming project while
            // this file lives in Generated/. Preserve its manifest-relative name
            // instead of producing Generated/Generated/ on the next generation.
            let root = Path.TrimEndingDirectorySeparator(Path.GetFullPath scan.Root)
            let prefix = root + string Path.DirectorySeparatorChar
            let mutable folder = DirectoryInfo(Path.GetDirectoryName source.Path)
            let mutable name = None
            while name.IsNone && not (isNull folder)
                  && (folder.FullName.Equals(root, StringComparison.OrdinalIgnoreCase) || folder.FullName.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)) do
                token.ThrowIfCancellationRequested()
                if File.Exists(Path.Combine(folder.FullName, ".anotheredit-poco.json")) then
                    let _, owned = PocoOutput.OwnedFiles folder.FullName
                    let relative = Path.GetRelativePath(folder.FullName, source.Path)
                    if owned |> Map.exists (fun path _ -> path.Equals(relative, StringComparison.OrdinalIgnoreCase)) then name <- Some relative
                folder <- folder.Parent
            defaultArg name source.RelativePath
        for path in included |> Seq.filter (refreshedSources.Contains >> not) |> Seq.sort do
            let source = filesByPath.[path]
            let text = (match edits.TryGetValue path with true, items -> ApplyEdits(source.Text, items.ToArray()) | _ -> source.Text) |> canonicalMappingRegions
            let text =
                let hasAnnotationDirective = roots.[path].DescendantTrivia(descendIntoTrivia = true) |> Seq.exists (fun trivia ->
                    match trivia.GetStructure() with
                    | :? NullableDirectiveTriviaSyntax as directive -> directive.TargetToken.ValueText <> "warnings"
                    | _ -> false)
                if not allowNullableSyntax then
                    // Older output may already contain directives inserted by the generator.
                    // Remove only directives, leaving nullable value types and other text intact.
                    if not (text.Contains('#')) then text
                    else
                        let syntax = CSharpSyntaxTree.ParseText(text, cancellationToken = token).GetRoot(token)
                        let directives =
                            syntax.DescendantTrivia(descendIntoTrivia = true)
                            |> Seq.filter (fun trivia -> trivia.IsKind(SyntaxKind.NullableDirectiveTrivia))
                            |> Seq.toArray
                        let result = StringBuilder(text)
                        for trivia in Array.rev directives do
                            result.Remove(trivia.FullSpan.Start, trivia.FullSpan.Length) |> ignore
                        result.ToString()
                elif not hasAnnotationDirective then
                    let newline = lineEnding source.Text |> Option.defaultValue Environment.NewLine
                    let directive = (if defaultAnnotations path then "#nullable enable annotations" else "#nullable disable annotations") + newline
                    if text.StartsWith("// <auto-generated by AnotherEdit>", StringComparison.Ordinal) && text.IndexOf('\n') >= 0 then
                        text.Insert(text.IndexOf('\n') + 1, directive)
                    else directive + text
                else text
            output.Add { FileName = outputName source; Text = text }
        for file, root in generatedRoots do
            // Procedure helpers and their partial-context facade share a file.
            // Facades were merged above into the original concrete context; retain
            // every DTO/executor while removing just duplicate declarations.
            let duplicates =
                root.DescendantNodes().OfType<BaseTypeDeclarationSyntax>()
                |> Seq.filter (fun declaration ->
                    let fullName = snd (sourceName declaration declaration.Identifier.ValueText)
                    fullName = context.FullName || preservedTypes.Contains fullName)
                |> Seq.filter (fun declaration ->
                    declaration.Ancestors().OfType<BaseTypeDeclarationSyntax>() |> Seq.isEmpty)
                |> Seq.map (fun declaration -> declaration :> SyntaxNode) |> Seq.toArray
            let updated = if duplicates.Length = 0 then root else root.RemoveNodes(duplicates, SyntaxRemoveOptions.KeepNoTrivia)
            if TypeDeclarations updated |> Seq.isEmpty |> not then output.Add { file with Text = updated.ToFullString() }
        { Files = output.ToArray(); Warnings = warnings |> Seq.distinct |> Seq.toArray }

    let GenerateCompatibleForProject(scan: PocoExistingScan, snapshot, options: PocoOptions, projectFile, token) =
        let language = NullableSyntaxForProject projectFile |> Option.orElseWith (fun () -> NullableSyntaxForProject scan.ProjectFile)
        let fallback = defaultArg scan.Target options.Target <> PocoTarget.Ef6 || scan.NullableReferenceTypes = Some true
