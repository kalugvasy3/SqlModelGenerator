    private static readonly Regex GeneratedMarker = new(@"^[\t ]*(?://|\*)[\t ]*<auto-generated(?:[\t ]*/)?[\t ]*>[\t \r]*$", RegexOptions.IgnoreCase | RegexOptions.Multiline);
    private static readonly HashSet<string> IgnoredDirectories = new(new[] { ".git", ".vs", "obj", "bin", "node_modules", "packages" }, StringComparer.OrdinalIgnoreCase);
    private static T? One<T>(IEnumerable<T?> values) where T : class
    {
        var found = values.Distinct().Take(2).ToArray();
        return found.Length == 1 ? found[0] : null;
    }
    private static T? OneValue<T>(IEnumerable<T> values) where T : struct
    {
        var found = values.Distinct().Take(2).ToArray();
        return found.Length == 1 ? found[0] : null;
    }
    private static string SimpleName(string text) => text[(Math.Max(text.LastIndexOf('.'), text.LastIndexOf(':')) + 1)..].TrimStart('@');
    private static IEnumerable<AttributeSyntax> Attributes(string name, SyntaxList<AttributeListSyntax> lists) => lists.SelectMany(x => x.Attributes).Where(x => SimpleName(x.Name.ToString()) is var n && (n == name || n == name + "Attribute"));
    private static string? LiteralText(ExpressionSyntax expression) => expression is LiteralExpressionSyntax literal && literal.IsKind(SyntaxKind.StringLiteralExpression) ? literal.Token.ValueText : null;
    private static string? AttributeValue(string name, string? argument, SyntaxList<AttributeListSyntax> lists) => One(Attributes(name, lists).Select(attribute =>
    {
        var item = attribute.ArgumentList?.Arguments.FirstOrDefault(item => argument == null
            ? item.NameEquals == null && item.NameColon == null
            : item.NameEquals?.Name.Identifier.ValueText == argument || item.NameColon?.Name.Identifier.ValueText == argument);
        return item == null ? null : LiteralText(item.Expression);
    }).Where(x => x != null));
    private static (string Namespace, string FullName) SourceName(SyntaxNode node, string name)
    {
        var scopes = string.Join(".", node.Ancestors().OfType<BaseNamespaceDeclarationSyntax>().Reverse().Select(x => x.Name.ToString().Replace("@", "")));
        var containing = node.Ancestors().OfType<TypeDeclarationSyntax>().Reverse().Select(x => x.Identifier.ValueText);
        return (scopes, string.Join(".", new[] { scopes }.Concat(containing).Append(name).Where(x => !string.IsNullOrEmpty(x))));
    }
    internal static IEnumerable<(string Name, int Kind)> TypeDeclarations(SyntaxNode root)
    {
        foreach (var node in root.DescendantNodes())
        {
            var name = node switch
            {
                TypeDeclarationSyntax t when t.TypeParameterList == null => t.Identifier.ValueText,
                EnumDeclarationSyntax e => e.Identifier.ValueText,
                DelegateDeclarationSyntax d when d.TypeParameterList == null => d.Identifier.ValueText,
                _ => null
            };
            if (name != null) yield return (SourceName(node, name).FullName, node.RawKind);
        }
    }
    private static (SyntaxNode Root, PocoExistingClass[] Classes, bool HasErrors) InspectText(string path, string relative, string text, string hash, bool bom, CancellationToken token)
    {
        var root = CSharpSyntaxTree.ParseText(text, cancellationToken: token).GetRoot(token);
        var generated = GeneratedMarker.IsMatch(root.GetLeadingTrivia().ToFullString());
        var conditions = root.DescendantTrivia(descendIntoTrivia: true).Any(t => t.IsKind(SyntaxKind.IfDirectiveTrivia) || t.IsKind(SyntaxKind.ElifDirectiveTrivia) || t.IsKind(SyntaxKind.ElseDirectiveTrivia) || t.IsKind(SyntaxKind.EndIfDirectiveTrivia));
        var errors = root.GetDiagnostics().Any(d => d.Severity == DiagnosticSeverity.Error);
        var classes = root.DescendantNodes().OfType<ClassDeclarationSyntax>().Select(node =>
        {
            var (ns, full) = SourceName(node, node.Identifier.ValueText);
            var properties = node.Members.OfType<PropertyDeclarationSyntax>().Where(p => p.Modifiers.Any(SyntaxKind.PublicKeyword) && !p.Modifiers.Any(SyntaxKind.StaticKeyword))
                .Select(p => new PocoExistingProperty(p.Identifier.ValueText, AttributeValue("Column", null, p.AttributeLists), p.Type.ToString(), p)).ToArray();
            return new PocoExistingClass(full, node.Identifier.ValueText, ns, path, relative, text, hash, bom,
                AttributeValue("Table", null, node.AttributeLists), AttributeValue("Table", "Schema", node.AttributeLists), null, properties, node, generated,
                !conditions && !errors && node.TypeParameterList == null);
        }).ToArray();
        return (root, classes, errors);
    }
    private static string? GenericArgument(string name, SyntaxNode syntax) => syntax.DescendantNodesAndSelf().OfType<GenericNameSyntax>().FirstOrDefault(x => x.Identifier.ValueText == name && x.TypeArgumentList.Arguments.Count == 1)?.TypeArgumentList.Arguments[0].ToString().Replace("global::", "");
    private static string MethodName(InvocationExpressionSyntax call) => call.Expression switch { MemberAccessExpressionSyntax a => a.Name.Identifier.ValueText, SimpleNameSyntax n => n.Identifier.ValueText, _ => "" };
    private static ExpressionSyntax? Receiver(InvocationExpressionSyntax call) => (call.Expression as MemberAccessExpressionSyntax)?.Expression;
    private static string? ReceiverName(InvocationExpressionSyntax call) => Receiver(call)?.ToString() ?? (call.Expression is SimpleNameSyntax ? "this" : null);
    private static string? LambdaParameter(LambdaExpressionSyntax lambda) => lambda switch
    {
        SimpleLambdaExpressionSyntax s => s.Parameter.Identifier.ValueText,
        ParenthesizedLambdaExpressionSyntax p when p.ParameterList.Parameters.Count == 1 => p.ParameterList.Parameters[0].Identifier.ValueText,
        _ => null
    };
    private sealed record FluentMappings(Dictionary<string, string?> Sets, Dictionary<string, (string Name, string? Schema)?> Tables, Dictionary<(string Entity, string Property), string?> Columns, HashSet<string> UnsupportedTables);
    private static FluentMappings GetFluentMappings(PocoExistingClass[] classes, SyntaxNode[] roots)
    {
        var fullNames = classes.Select(x => x.FullName).ToHashSet(StringComparer.Ordinal);
        var shortNames = classes.GroupBy(x => x.Name).ToDictionary(g => g.Key, g => One(g.Select(x => x.FullName)), StringComparer.Ordinal);
        string? ResolveClass(string? typeName) => typeName == null ? null : fullNames.Contains(typeName) ? typeName : typeName.Contains('.') ? null : shortNames.GetValueOrDefault(SimpleName(typeName));
        var sets = new List<(string Entity, string Name)>();
        var tables = new List<(string Entity, (string Name, string? Schema) Table)>();
        var columns = new List<((string Entity, string Property) Key, string Column)>();
        var unsupported = new HashSet<string>(StringComparer.Ordinal);
        string? EntityFor(InvocationExpressionSyntax node)
        {
            var receiver = Receiver(node);
            string? name = null;
            if (receiver != null)
            {
                var calls = receiver.DescendantNodesAndSelf().OfType<InvocationExpressionSyntax>().ToArray();
                name = calls.Length == 0 ? receiver.ToString() : ReceiverName(calls[^1]);
            }
            name ??= ReceiverName(node);
            var direct = receiver == null ? null : ResolveClass(GenericArgument("Entity", receiver));
            string? local = null;
            if (name != null)
                local = node.Ancestors().OfType<BlockSyntax>().Select(block => One(block.Statements.OfType<LocalDeclarationStatementSyntax>().SelectMany(s => s.Declaration.Variables)
                    .Where(v => v.Identifier.ValueText == name && v.SpanStart < node.SpanStart && v.Initializer != null)
                    .Select(v => ResolveClass(GenericArgument("Entity", v.Initializer!.Value))).Where(x => x != null))).FirstOrDefault(x => x != null);
            var enclosing = node.Ancestors().OfType<LambdaExpressionSyntax>().Select(lambda => LambdaParameter(lambda) != null && LambdaParameter(lambda) == name && lambda.Parent is ArgumentSyntax a && a.Parent?.Parent is InvocationExpressionSyntax call ? ResolveClass(GenericArgument("Entity", call.Expression)) : null).FirstOrDefault(x => x != null);
            var configuration = node.Ancestors().OfType<ClassDeclarationSyntax>().Select(declaration =>
            {
                if (declaration.BaseList == null) return null;
                if (name == "this") return ResolveClass(GenericArgument("EntityTypeConfiguration", declaration.BaseList));
                return node.Ancestors().OfType<MethodDeclarationSyntax>().Where(m => m.Identifier.ValueText == "Configure")
                    .Select(m => m.ParameterList.Parameters.FirstOrDefault(p => p.Identifier.ValueText == name && p.Type != null))
                    .Select(p => p == null ? null : ResolveClass(GenericArgument("EntityTypeBuilder", p.Type!))).FirstOrDefault(x => x != null);
            }).FirstOrDefault(x => x != null);
            return direct ?? local ?? enclosing ?? configuration;
        }
        foreach (var root in roots)
        {
            foreach (var declaration in root.DescendantNodes().OfType<PropertyDeclarationSyntax>())
                if (ResolveClass(GenericArgument("DbSet", declaration.Type)) is { } entity) sets.Add((entity, declaration.Identifier.ValueText));
            foreach (var call in root.DescendantNodes().OfType<InvocationExpressionSyntax>())
            {
                if (call.ArgumentList.Arguments.Count == 0) continue;
                var name = LiteralText(call.ArgumentList.Arguments[0].Expression);
                var entity = EntityFor(call);
                if (MethodName(call) is "ToTable" or "ToView")
                {
                    if (entity == null) continue;
                    if (name == null) { unsupported.Add(entity); continue; }
                    var schema = call.ArgumentList.Arguments.Count < 2 ? null : LiteralText(call.ArgumentList.Arguments[1].Expression);
                    tables.Add((entity, (name, schema)));
                    if (call.ArgumentList.Arguments.Count >= 2 && schema == null && call.ArgumentList.Arguments[1].Expression is not LambdaExpressionSyntax) unsupported.Add(entity);
                }
                else if (MethodName(call) == "HasColumnName" && entity != null && name != null && Receiver(call) is InvocationExpressionSyntax property && MethodName(property) == "Property" && property.ArgumentList.Arguments.Count == 1 && property.ArgumentList.Arguments[0].Expression is LambdaExpressionSyntax lambda && lambda.Body is MemberAccessExpressionSyntax access && LambdaParameter(lambda) == access.Expression.ToString())
                    columns.Add(((entity, access.Name.Identifier.ValueText), name));
            }
        }
        return new(sets.GroupBy(x => x.Entity).ToDictionary(g => g.Key, g => One(g.Select(x => x.Name)), StringComparer.Ordinal),
            tables.GroupBy(x => x.Entity).ToDictionary(g => g.Key, g => OneValue(g.Select(x => x.Table)), StringComparer.Ordinal),
            columns.GroupBy(x => x.Key).ToDictionary(g => g.Key, g => One(g.Select(x => x.Column))), unsupported);
    }

    internal static ((string FullName, string Name)[] Classes, (string FullName, string Context, string Property, string Entity)[] Sets,
        IReadOnlyDictionary<string, (string Table, string? Schema)?> Tables, (string Entity, string Property, string? Column)[] Properties, bool HasErrors)
        ReadSourceMappings(string text, CancellationToken token)
    {
        var (root, classes, errors) = InspectText("", "", text, "", false, token);
        var fluent = GetFluentMappings(classes, new[] { root });
        var tables = new Dictionary<string, (string, string?)?>(StringComparer.Ordinal);
        foreach (var group in classes.GroupBy(x => x.FullName))
        {
            if (fluent.UnsupportedTables.Contains(group.Key)) { tables[group.Key] = null; continue; }
            if (fluent.Tables.TryGetValue(group.Key, out var mapped)) { tables[group.Key] = mapped; continue; }
            var declarations = group.Where(x => Attributes("Table", x.Declaration.AttributeLists).Any()).ToArray();
            if (declarations.Length == 0) continue;
            var values = declarations.Select(d =>
            {
                var explicitSchema = Attributes("Table", d.Declaration.AttributeLists).Any(a => a.ArgumentList != null && a.ArgumentList.Arguments.Any(arg => arg.NameEquals?.Name.Identifier.ValueText == "Schema" || arg.NameColon?.Name.Identifier.ValueText == "Schema"));
                return explicitSchema && d.Schema == null || d.TableName == null ? ((string, string?)?)null : (d.TableName!, d.Schema);
            }).ToArray();
            tables[group.Key] = values.Any(x => x == null) ? null : OneValue(values.Select(x => x!.Value));
        }
        var sets = classes.SelectMany(context => context.Properties.Select(p => (Context: context, Property: p, Entity: GenericArgument("DbSet", p.Declaration.Type) ?? GenericArgument("IDbSet", p.Declaration.Type))).Where(x => x.Entity != null)
            .Select(x => (x.Context.FullName, x.Context.Name, x.Property.Name, x.Entity!))).ToArray();
        var properties = classes.SelectMany(entity => entity.Properties.Where(p => !Attributes("NotMapped", p.Declaration.AttributeLists).Any()).Select(p =>
        {
            var column = fluent.Columns.TryGetValue((entity.FullName, p.Name), out var mapping) ? mapping : p.ColumnName == null && Attributes("Column", p.Declaration.AttributeLists).Any() ? null : p.ColumnName ?? p.Name;
            return (entity.FullName, p.Name, column);
        })).ToArray();
        return (classes.Select(x => (x.FullName, x.Name)).Distinct().ToArray(), sets, tables, properties, errors);
    }

    private static IEnumerable<string> SourcePaths(string root, CancellationToken token)
    {
        var pending = new Stack<string>(); pending.Push(root);
        var options = new EnumerationOptions { AttributesToSkip = FileAttributes.ReparsePoint, IgnoreInaccessible = false };
        while (pending.Count > 0)
        {
            token.ThrowIfCancellationRequested();
            var folder = pending.Pop();
            foreach (var file in Directory.EnumerateFiles(folder, "*.cs", options)) yield return file;
            foreach (var child in Directory.EnumerateDirectories(folder, "*", options)) if (!IgnoredDirectories.Contains(Path.GetFileName(child))) pending.Push(child);
        }
    }
    private static string ProjectPathKey(string path)
    {
        var normalized = path.Replace('\\', '/');
        return (normalized.StartsWith("./", StringComparison.Ordinal) ? normalized[2..] : normalized).ToUpperInvariant();
    }
    private static string[] FindProjects(string path, CancellationToken token)
    {
        var input = Path.GetFullPath(path);
        if (File.Exists(input) && Path.GetExtension(input).Equals(".csproj", StringComparison.OrdinalIgnoreCase)) return new[] { input };
        var folder = new DirectoryInfo(File.Exists(input) ? Path.GetDirectoryName(input)! : input);
        var options = new EnumerationOptions { AttributesToSkip = FileAttributes.ReparsePoint, IgnoreInaccessible = true };
        for (; folder != null; folder = folder.Parent)
        {
            token.ThrowIfCancellationRequested();
            if (!folder.Exists) continue;
            var projects = folder.EnumerateFiles("*.csproj", options).Take(2).Select(x => x.FullName).ToArray();
            if (projects.Length != 0) return projects;
        }
        return Array.Empty<string>();
    }
    public static string? FindProject(string path, CancellationToken token) => One(FindProjects(path, token));
    public static bool? NullableSyntaxForProject(string? projectFile)
    {
        if (projectFile == null || !File.Exists(projectFile) || new FileInfo(projectFile).Length > 1048576) return null;
        var xml = XDocument.Load(projectFile);
        IEnumerable<XElement> Properties(string name) => xml.Descendants().Where(n => n.Name.LocalName == name);
        bool? Version(XElement node) => LanguageVersionFacts.TryParse(node.Value.Trim(), out var version) ? new CSharpParseOptions(version).LanguageVersion >= LanguageVersion.CSharp8 : null;
        var languages = Properties("LangVersion").ToArray();
        if (languages.Any(n => Version(n) == false)) return false;
        if (languages.Any(n => Version(n) == true && n.AncestorsAndSelf().All(a => a.Attribute("Condition") == null))) return true;
        var targets = Properties("TargetFramework").Concat(Properties("TargetFrameworks")).SelectMany(n => n.Value.Split(';', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries)).ToArray();
        var legacyFramework = Properties("TargetFrameworkVersion").Any(n => Regex.IsMatch(n.Value.Trim(), @"^[vV]4\.\d+(?:\.\d+)?$"));
        var legacyTarget = targets.Any(t => Regex.IsMatch(t, @"^net(?:4[0-9]{1,2}|(?:coreapp[12]|standard[12])\.\d+)$", RegexOptions.IgnoreCase) && !t.Equals("netstandard2.1", StringComparison.OrdinalIgnoreCase));
        if (legacyFramework || legacyTarget) return false;
        if (targets.Length > 0 && targets.All(t => Regex.IsMatch(t, @"^net(?:(?:[5-9]|[1-9]\d+)\.\d+(?:-|$)|coreapp3\.\d+$|standard2\.1$)", RegexOptions.IgnoreCase))) return true;
        return null;
    }
    private sealed record ProjectInformation(PocoTarget[] Targets, string? Namespace, bool? Nullable, (string Project, HashSet<string> Generated)? Generated);
    private static ProjectInformation ProjectInfo(string path, List<string> warnings, CancellationToken token)
    {
        var projects = FindProjects(path, token);
        if (projects.Length != 1 || new FileInfo(projects[0]).Length > 1048576)
        {
            if (projects.Length > 1) warnings.Add("Several projects are in the nearest project folder. Select a .csproj to detect its EF version.");
            return new(Array.Empty<PocoTarget>(), null, null, null);
        }
        var project = projects[0]; var xml = XDocument.Load(project);
        var packages = xml.Descendants().Where(x => x.Name.LocalName is "PackageReference" or "Reference").Select(x => (string?)x.Attribute("Include")).Where(x => x != null).Select(x => x!.Split(',')[0].Trim()).ToArray();
        var ef6 = packages.Any(p => p.Equals("EntityFramework", StringComparison.OrdinalIgnoreCase));
        var core = packages.Any(p => p.Equals("Microsoft.EntityFrameworkCore", StringComparison.OrdinalIgnoreCase) || p.StartsWith("Microsoft.EntityFrameworkCore.", StringComparison.OrdinalIgnoreCase));
        if (ef6 && core) warnings.Add("The project references both EF6 and EF Core. Choose the target explicitly.");
        string? ReadProperty(string name) => One(xml.Descendants().Where(n => n.Name.LocalName == name).Select(n => n.Value.Trim()).Where(v => !string.IsNullOrWhiteSpace(v)));
        bool? nullable = ReadProperty("Nullable") switch { "enable" or "annotations" => true, "disable" or "warnings" => false, _ => null };
        var compile = xml.Descendants().Where(n => n.Name.LocalName == "Compile").ToArray();
        if (compile.Any(n => n.Attribute("Include") != null || n.Attribute("Remove") != null)) warnings.Add("The project contains explicit Compile rules. The scan covers the selected directory and may include files outside the build.");
        var generated = new HashSet<string>(StringComparer.Ordinal);
        foreach (var item in compile)
        {
            var autoGen = item.Elements().FirstOrDefault(n => n.Name.LocalName == "AutoGen");
            var dependency = item.Elements().FirstOrDefault(n => n.Name.LocalName == "DependentUpon");
            if (autoGen?.Value.Trim().Equals("true", StringComparison.OrdinalIgnoreCase) == true && !string.IsNullOrWhiteSpace(dependency?.Value))
            {
                var value = item.Attribute("Update")?.Value ?? item.Attribute("Include")?.Value;
                if (value != null) generated.Add(ProjectPathKey(value));
            }
        }
        return new((ef6 ? new[] { PocoTarget.Ef6 } : Array.Empty<PocoTarget>()).Concat(core ? new[] { PocoTarget.EfCore } : Array.Empty<PocoTarget>()).ToArray(), ReadProperty("RootNamespace"), nullable, (project, generated));
    }
    private static PocoExistingClass[] ContextCandidates(PocoExistingClass[] classes)
    {
        var contexts = classes.Where(x => x.Declaration.BaseList != null && x.Declaration.TypeParameterList == null && !x.Declaration.Modifiers.Any(SyntaxKind.AbstractKeyword)
            && x.Declaration.Parent is BaseNamespaceDeclarationSyntax or CompilationUnitSyntax && x.Declaration.BaseList.Types.Any(b => SimpleName(b.Type.ToString()) == "DbContext")).ToArray();
        var mapped = contexts.Where(x => x.Properties.Any(p => GenericArgument("DbSet", p.Declaration.Type) != null) || x.Declaration.Members.OfType<MethodDeclarationSyntax>().Any(m => m.Identifier.ValueText == "OnModelCreating" && m.Modifiers.Any(SyntaxKind.OverrideKeyword))).ToArray();
        var candidates = mapped.Length > 0 ? mapped : contexts;
        var original = candidates.Where(x => !x.Text.StartsWith("// <auto-generated by AnotherEdit>", StringComparison.Ordinal)).ToArray();
        return (original.Length > 0 ? original : candidates).DistinctBy(x => x.FullName).ToArray();
    }
    private static PocoTarget? FrameworkFromSource(PocoExistingClass[] contexts)
    {
        var names = contexts.SelectMany(c => c.Declaration.BaseList!.Types.Select(t => t.Type.ToString()).Concat(c.Declaration.SyntaxTree.GetRoot().DescendantNodes().OfType<UsingDirectiveSyntax>().Where(u => u.Name != null).Select(u => u.Name!.ToString())));
        return OneValue(names.Select(n => n.Replace("global::", "") switch { "Microsoft.EntityFrameworkCore" or "Microsoft.EntityFrameworkCore.DbContext" => (PocoTarget?)PocoTarget.EfCore, "System.Data.Entity" or "System.Data.Entity.DbContext" => PocoTarget.Ef6, _ => null }).Where(x => x.HasValue).Select(x => x!.Value));
    }
    private static PocoExistingScan AnalyzeSources(string root, ProjectInformation info, PocoExistingSource[] sources, List<string> warnings, CancellationToken token)
    {
        var roots = new List<SyntaxNode>(); var parsed = new List<PocoExistingClass>(); var declared = new List<(string Name, string File, int Kind)>();
        foreach (var source in sources)
        {
            token.ThrowIfCancellationRequested();
            var (syntax, classes, bad) = InspectText(source.Path, source.RelativePath, source.Text, source.SourceHash, source.HasUtf8Bom, token);
            if (bad) warnings.Add(source.RelativePath + " has C# syntax errors and is protected from updates.");
            roots.Add(syntax); declared.AddRange(TypeDeclarations(syntax).Select(d => (d.Name, source.RelativePath, d.Kind))); parsed.AddRange(classes);
        }
        var sorted = parsed.OrderBy(x => x.FullName, StringComparer.Ordinal).ThenBy(x => x.RelativePath, StringComparer.Ordinal).ToArray();
        var fluent = GetFluentMappings(sorted, roots.ToArray());
        var mapped = sorted.Select(item =>
        {
            var hasTable = fluent.Tables.TryGetValue(item.FullName, out var table);
            var props = item.Properties.Select(p => fluent.Columns.TryGetValue((item.FullName, p.Name), out var column) && column != null ? p with { ColumnName = column } : p).ToArray();
            var ambiguous = item.Properties.Any(p => fluent.Columns.TryGetValue((item.FullName, p.Name), out var column) && column == null);
            var generated = item.GeneratedSource && (info.Generated == null || info.Generated.Value.Generated.Contains(ProjectPathKey(Path.GetRelativePath(Path.GetDirectoryName(info.Generated.Value.Project)!, item.Path))));
            return item with { TableName = table?.Name ?? item.TableName, Schema = table.HasValue ? table.Value.Schema : item.Schema, Properties = props, GeneratedSource = generated, SetName = fluent.Sets.GetValueOrDefault(item.FullName), CanEdit = item.CanEdit && !(hasTable && table == null) && !ambiguous };
        }).ToArray();
        foreach (var entry in fluent.Tables.OrderBy(x => x.Key, StringComparer.Ordinal)) if (entry.Value == null) warnings.Add(entry.Key + " has conflicting table mappings. Existing code is protected.");
        foreach (var entry in fluent.Columns.OrderBy(x => x.Key.Entity, StringComparer.Ordinal).ThenBy(x => x.Key.Property, StringComparer.Ordinal)) if (entry.Value == null) warnings.Add(entry.Key.Entity + "." + entry.Key.Property + " has conflicting column mappings. Existing code is protected.");
        var conflicts = new HashSet<string>(StringComparer.Ordinal);
        var types = declared.GroupBy(x => x.Name).ToDictionary(g => g.Key, g =>
        {
            var entries = g.ToArray(); var files = entries.Select(x => x.File).ToArray();
            if (entries.Select(x => x.Kind).Distinct().Count() > 1) { conflicts.Add(g.Key); warnings.Add(g.Key + " has conflicting type declarations in " + string.Join(", ", files.Distinct()) + "."); }
            return files;
        }, StringComparer.Ordinal);
        var contexts = ContextCandidates(mapped.Where(x => !conflicts.Contains(x.FullName)).ToArray());
        var context = contexts.Length == 1 ? contexts[0] : null;
        var target = info.Targets.Length == 0 ? FrameworkFromSource(contexts) : OneValue(info.Targets);
        var modelNamespace = One(mapped.Where(x => x.TableName != null || x.SetName != null).Select(x => x.Namespace).Where(x => !string.IsNullOrWhiteSpace(x)));
        var sourceNamespace = One(mapped.Select(x => x.Namespace).Where(x => !string.IsNullOrWhiteSpace(x)));
        PocoNaming? InferredNaming(Func<PocoExistingClass, string?> pick) => OneValue(mapped.Select(x =>
        {
            var table = x.TableName ?? x.SetName; var name = pick(x);
            return table == null || name == null ? (PocoNaming?)null : name == table ? PocoNaming.AsInDatabase : table == name + "s" || table == name + "es" ? PocoNaming.Singular : name == table + "s" || name == table + "es" ? PocoNaming.Plural : null;
        }).Where(x => x.HasValue).Select(x => x!.Value));
        return new(root, info.Generated?.Project, mapped, sources, types, target, context?.Namespace ?? modelNamespace ?? sourceNamespace ?? info.Namespace ?? "", context?.Name ?? "", contexts.Select(x => x.FullName).ToArray(), info.Nullable, InferredNaming(x => x.Name), InferredNaming(x => x.SetName), warnings.ToArray());
    }
    public static PocoExistingScan Scan(string path, CancellationToken token)
    {
        var input = Path.GetFullPath(path); var directory = Directory.Exists(input);
        if (!directory && !File.Exists(input)) throw new ArgumentException("Choose an existing C# folder or project.", nameof(path));
        if ((File.GetAttributes(input) & FileAttributes.ReparsePoint) != 0) throw new ArgumentException("Choose a folder or project that is not a filesystem link.", nameof(path));
        var extension = Path.GetExtension(input); var isSource = !directory && extension.Equals(".cs", StringComparison.OrdinalIgnoreCase);
        if (!directory && !isSource && !extension.Equals(".csproj", StringComparison.OrdinalIgnoreCase)) throw new ArgumentException("Choose a C# file, project, or folder.", nameof(path));
        var root = directory ? input : Path.GetDirectoryName(input)!;
        var warnings = new List<string>(); var info = ProjectInfo(input, warnings, token); var sources = new List<PocoExistingSource>();
        var files = (isSource ? new[] { input } : SourcePaths(root, token)).Take(1001).ToArray();
        if (files.Length > 1000) throw new InvalidOperationException("The C# scan exceeded 1,000 files. Select a smaller model folder.");
        long totalBytes = 0;
        foreach (var file in files)
        {
            token.ThrowIfCancellationRequested(); var relative = Path.GetRelativePath(root, file);
            try
            {
                using var stream = new FileStream(file, FileMode.Open, FileAccess.Read, FileShare.Read);
                var length = stream.Length;
                if (length > 2097152) { warnings.Add(relative + " exceeds the 2 MiB source-file limit and was skipped."); continue; }
                totalBytes += length;
                if (totalBytes > 33554432) throw new InvalidOperationException("The C# scan exceeded 32 MiB. Select a smaller model folder.");
                var bytes = new byte[(int)length]; stream.ReadExactly(bytes);
                var bom = bytes.Length >= 3 && bytes[0] == 239 && bytes[1] == 187 && bytes[2] == 191; var offset = bom ? 3 : 0;
                var text = Utf8.GetString(bytes, offset, bytes.Length - offset);
                if (text.IndexOf('\0') >= 0) { warnings.Add(relative + " is not UTF-8 C# and was skipped."); continue; }
                sources.Add(new(file, relative, text, Convert.ToHexString(SHA256.HashData(bytes)), bom));
            }
            catch (DecoderFallbackException) { warnings.Add(relative + " is not UTF-8 C# and was skipped."); }
        }
        return AnalyzeSources(root, info, sources.ToArray(), warnings, token);
    }
